package com.skycraft.fire;

import com.skycraft.Skycraft;
import net.minecraft.world.item.BlockItem;
import net.minecraft.world.item.Item;
import net.minecraft.world.level.block.Block;
import net.minecraft.world.level.block.RotatedPillarBlock;
import net.minecraft.world.level.block.SlabBlock;
import net.minecraft.world.level.block.SoundType;
import net.minecraft.world.level.block.StairBlock;
import net.minecraft.world.level.block.state.BlockBehaviour;
import net.minecraft.world.level.material.MapColor;
import net.minecraft.world.level.material.PushReaction;
import net.minecraft.world.phys.shapes.VoxelShape;
import net.minecraftforge.eventbus.api.IEventBus;
import net.minecraftforge.registries.DeferredRegister;
import net.minecraftforge.registries.ForgeRegistries;
import net.minecraftforge.registries.RegistryObject;

/**
 * Blocks of the fire module: the big fire family (emissive, animated, persistent, never spreading), the charred and
 * scorched building set for ruins, and the ground decals and debris of an aftermath. Textures, models and blockstates
 * are generated by {@code tools/textures/fire.py}.
 */
public final class FireBlocks {
    public static final DeferredRegister<Block> BLOCKS = DeferredRegister.create(ForgeRegistries.BLOCKS, Skycraft.MODID);
    public static final DeferredRegister<Item> ITEMS = DeferredRegister.create(ForgeRegistries.ITEMS, Skycraft.MODID);

    // ---- big fire family
    public static final RegistryObject<Block> BIG_FIRE = fire("big_fire", BigFireBlock.Kind.BASE);
    public static final RegistryObject<Block> FLAME_COLUMN = fire("flame_column", BigFireBlock.Kind.COLUMN);
    public static final RegistryObject<Block> FLAME_TIP = fire("flame_tip", BigFireBlock.Kind.TIP);
    public static final RegistryObject<Block> RUBBLE_FIRE = fire("rubble_fire", BigFireBlock.Kind.RUBBLE);
    public static final RegistryObject<Block> SMOULDERING_EMBERS = fire("smouldering_embers", BigFireBlock.Kind.EMBERS);

    // ---- charred and scorched building blocks
    public static final RegistryObject<Block> CHARRED_PLANKS = block("charred_planks",
            () -> new Block(BlockBehaviour.Properties.of().mapColor(MapColor.COLOR_BLACK).strength(1.2f, 3.0f).sound(SoundType.WOOD)));
    public static final RegistryObject<Block> CHARRED_PLANKS_STAIRS = block("charred_planks_stairs",
            () -> new StairBlock(() -> CHARRED_PLANKS.get().defaultBlockState(), BlockBehaviour.Properties.copy(CHARRED_PLANKS.get())));
    public static final RegistryObject<Block> CHARRED_PLANKS_SLAB = block("charred_planks_slab",
            () -> new SlabBlock(BlockBehaviour.Properties.copy(CHARRED_PLANKS.get())));
    public static final RegistryObject<Block> CHARRED_LOG = block("charred_log",
            () -> new RotatedPillarBlock(BlockBehaviour.Properties.of().mapColor(MapColor.COLOR_BLACK).strength(1.6f, 3.0f).sound(SoundType.WOOD)));
    public static final RegistryObject<Block> CHARRED_BEAM = block("charred_beam",
            () -> new RotatedPillarBlock(BlockBehaviour.Properties.of().mapColor(MapColor.COLOR_BLACK).strength(1.4f, 3.0f).sound(SoundType.WOOD)));
    public static final RegistryObject<Block> SCORCHED_STONE = block("scorched_stone",
            () -> new Block(BlockBehaviour.Properties.of().mapColor(MapColor.COLOR_GRAY).strength(1.8f, 5.0f).sound(SoundType.STONE)));
    public static final RegistryObject<Block> SCORCHED_STONE_BRICKS = block("scorched_stone_bricks",
            () -> new Block(BlockBehaviour.Properties.of().mapColor(MapColor.COLOR_GRAY).strength(1.8f, 5.0f).sound(SoundType.STONE)));

    // ---- decals and debris
    public static final RegistryObject<Block> SOOT_STAIN = block("soot_stain", () -> decal(MapColor.COLOR_BLACK));
    public static final RegistryObject<Block> BLOOD_STAIN = block("blood_stain", () -> decal(MapColor.COLOR_RED));
    public static final RegistryObject<Block> TIMBER_DEBRIS = block("timber_debris", () -> debris(Block.box(0, 0, 0, 16, 4, 16), false));
    public static final RegistryObject<Block> SPLINTERED_WRECKAGE = block("splintered_wreckage",
            () -> debris(Block.box(1, 0, 1, 15, 7, 15), true));
    public static final RegistryObject<Block> STUCK_ARROWS = block("stuck_arrows", () -> debris(Block.box(3, 0, 3, 13, 9, 13), false));

    private FireBlocks() {}

    private static RegistryObject<Block> fire(String name, BigFireBlock.Kind kind) {
        return block(name, () -> new BigFireBlock(kind, BlockBehaviour.Properties.of().mapColor(MapColor.FIRE).noCollission().replaceable()
                .strength(0.3f, 3600000.0f).lightLevel(s -> kind.light).sound(SoundType.WOOL).pushReaction(PushReaction.DESTROY)
                .noOcclusion().noLootTable()));
    }

    private static GroundDecalBlock decal(MapColor color) {
        return new GroundDecalBlock(BlockBehaviour.Properties.of().mapColor(color).noCollission().replaceable().instabreak()
                .sound(SoundType.WOOL).pushReaction(PushReaction.DESTROY).noOcclusion());
    }

    private static GroundDecalBlock debris(VoxelShape shape, boolean collide) {
        return new GroundDecalBlock(BlockBehaviour.Properties.of().mapColor(MapColor.COLOR_BROWN).strength(0.4f).sound(SoundType.WOOD)
                .pushReaction(PushReaction.DESTROY).noOcclusion(), shape, collide);
    }

    private static RegistryObject<Block> block(String name, java.util.function.Supplier<Block> factory) {
        RegistryObject<Block> b = BLOCKS.register(name, factory);
        ITEMS.register(name, () -> new BlockItem(b.get(), new Item.Properties()));
        return b;
    }

    static void init(IEventBus modBus) {
        BLOCKS.register(modBus);
        ITEMS.register(modBus);
    }
}
