package com.skycraft.fire;

import com.skycraft.Skycraft;
import net.minecraft.world.item.BlockItem;
import net.minecraft.world.item.Item;
import net.minecraft.world.level.block.Block;
import net.minecraft.world.level.block.RotatedPillarBlock;
import net.minecraft.world.level.block.SlabBlock;
import net.minecraft.world.level.block.SoundType;
import net.minecraft.world.level.block.StairBlock;
import net.minecraft.world.level.block.state.BlockBehaviour;
import net.minecraft.world.level.material.MapColor;
import net.minecraft.world.level.material.PushReaction;
import net.minecraft.world.phys.shapes.VoxelShape;
import net.neoforged.bus.api.IEventBus;
import net.neoforged.neoforge.registries.DeferredRegister;
import net.minecraft.core.registries.BuiltInRegistries;
import java.util.function.Supplier;

/**
 * Blocks of the fire module: the big fire family (emissive, animated, persistent, never spreading), the charred and
 * scorched building set for ruins, and the ground decals and debris of an aftermath. Textures, models and blockstates
 * are generated by {@code tools/textures/fire.py}.
 */
public final class FireBlocks {
    public static final DeferredRegister<Block> BLOCKS = DeferredRegister.create(BuiltInRegistries.BLOCK, Skycraft.MODID);
    public static final DeferredRegister<Item> ITEMS = DeferredRegister.create(BuiltInRegistries.ITEM, Skycraft.MODID);

    // ---- big fire family
    public static final Supplier<Block> BIG_FIRE = fire("big_fire", BigFireBlock.Kind.BASE);
    public static final Supplier<Block> FLAME_COLUMN = fire("flame_column", BigFireBlock.Kind.COLUMN);
    public static final Supplier<Block> FLAME_TIP = fire("flame_tip", BigFireBlock.Kind.TIP);
    public static final Supplier<Block> RUBBLE_FIRE = fire("rubble_fire", BigFireBlock.Kind.RUBBLE);
    public static final Supplier<Block> SMOULDERING_EMBERS = fire("smouldering_embers", BigFireBlock.Kind.EMBERS);

    // ---- charred and scorched building blocks
    public static final Supplier<Block> CHARRED_PLANKS = block("charred_planks",
            () -> new Block(com.skycraft.platform.SkyProperties.block("charred_planks").mapColor(MapColor.COLOR_BLACK).strength(1.2f, 3.0f).sound(SoundType.WOOD)));
    public static final Supplier<Block> CHARRED_PLANKS_STAIRS = block("charred_planks_stairs",
            () -> new StairBlock(CHARRED_PLANKS.get().defaultBlockState(), com.skycraft.platform.SkyProperties.block("charred_planks_stairs", BlockBehaviour.Properties.ofFullCopy(CHARRED_PLANKS.get()))));
    public static final Supplier<Block> CHARRED_PLANKS_SLAB = block("charred_planks_slab",
            () -> new SlabBlock(com.skycraft.platform.SkyProperties.block("charred_planks_slab", BlockBehaviour.Properties.ofFullCopy(CHARRED_PLANKS.get()))));
    public static final Supplier<Block> CHARRED_LOG = block("charred_log",
            () -> new RotatedPillarBlock(com.skycraft.platform.SkyProperties.block("charred_log").mapColor(MapColor.COLOR_BLACK).strength(1.6f, 3.0f).sound(SoundType.WOOD)));
    public static final Supplier<Block> CHARRED_BEAM = block("charred_beam",
            () -> new RotatedPillarBlock(com.skycraft.platform.SkyProperties.block("charred_beam").mapColor(MapColor.COLOR_BLACK).strength(1.4f, 3.0f).sound(SoundType.WOOD)));
    public static final Supplier<Block> SCORCHED_STONE = block("scorched_stone",
            () -> new Block(com.skycraft.platform.SkyProperties.block("scorched_stone").mapColor(MapColor.COLOR_GRAY).strength(1.8f, 5.0f).sound(SoundType.STONE)));
    public static final Supplier<Block> SCORCHED_STONE_BRICKS = block("scorched_stone_bricks",
            () -> new Block(com.skycraft.platform.SkyProperties.block("scorched_stone_bricks").mapColor(MapColor.COLOR_GRAY).strength(1.8f, 5.0f).sound(SoundType.STONE)));

    // ---- decals and debris
    public static final Supplier<Block> SOOT_STAIN = block("soot_stain", () -> decal("soot_stain", MapColor.COLOR_BLACK));
    public static final Supplier<Block> BLOOD_STAIN = block("blood_stain", () -> decal("blood_stain", MapColor.COLOR_RED));
    public static final Supplier<Block> TIMBER_DEBRIS = block("timber_debris", () -> debris("timber_debris", Block.box(0, 0, 0, 16, 4, 16), false));
    public static final Supplier<Block> SPLINTERED_WRECKAGE = block("splintered_wreckage",
            () -> debris("splintered_wreckage", Block.box(1, 0, 1, 15, 7, 15), true));
    public static final Supplier<Block> STUCK_ARROWS = block("stuck_arrows", () -> debris("stuck_arrows", Block.box(3, 0, 3, 13, 9, 13), false));

    private FireBlocks() {}

    private static Supplier<Block> fire(String name, BigFireBlock.Kind kind) {
        return block(name, () -> new BigFireBlock(kind, com.skycraft.platform.SkyProperties.block(name).mapColor(MapColor.FIRE).noCollision().replaceable()
                .strength(0.3f, 3600000.0f).lightLevel(s -> kind.light).sound(SoundType.WOOL).pushReaction(PushReaction.POPPED)
                .noOcclusion().noLootTable()));
    }

    private static GroundDecalBlock decal(String name, MapColor color) {
        return new GroundDecalBlock(com.skycraft.platform.SkyProperties.block(name).mapColor(color).noCollision().replaceable().instabreak()
                .sound(SoundType.WOOL).pushReaction(PushReaction.POPPED).noOcclusion());
    }

    private static GroundDecalBlock debris(String name, VoxelShape shape, boolean collide) {
        return new GroundDecalBlock(com.skycraft.platform.SkyProperties.block(name).mapColor(MapColor.COLOR_BROWN).strength(0.4f).sound(SoundType.WOOD)
                .pushReaction(PushReaction.POPPED).noOcclusion(), shape, collide);
    }

    private static Supplier<Block> block(String name, java.util.function.Supplier<Block> factory) {
        Supplier<Block> b = BLOCKS.register(name, factory);
        ITEMS.register(name, () -> new BlockItem(b.get(), com.skycraft.platform.SkyProperties.item(name)));
        return b;
    }

    static void init(IEventBus modBus) {
        BLOCKS.register(modBus);
        ITEMS.register(modBus);
    }
}
