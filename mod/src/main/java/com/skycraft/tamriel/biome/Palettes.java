/**
 * The biome palettes of Nirn ({@code skycraft/tamriel/palettes.json}, generated by tools/worldgen/biomes.py): for each
 * region (and each province, sea and realm archetype as fallbacks) the weighted biome choices of every terrain
 * context, plus optional ordered topographic micro-biome rules. Loaded once from the class path; {@link #compile}
 * resolves the biome keys against a registry lookup into immutable, thread-safe tables for the biome source.
 */
public final class Palettes {
    /** Terrain contexts, in the order of palettes.json's "contexts". */
    public enum Context {
        OCEAN, DEEP_OCEAN, BEACH, RIVER, LAKE, MARSH, LOWLAND, UPLAND, PEAK, SUMMIT, CAVE, DEEP_CAVE;

        public final String key = name().toLowerCase(java.util.Locale.ROOT);
    }

    public static final String SURFACE = "@surface";
    private static final String PATH = "/skycraft/tamriel/palettes.json";
    private static final MicroRule[] NO_MICRO = new MicroRule[0];
    private static volatile JsonObject raw;

    private Palettes() {}

    /** The parsed palettes.json (cached). */
    public static JsonObject raw() {
        JsonObject r = raw;
        if (r == null) {
            synchronized (Palettes.class) {
                r = raw;
                if (r == null) {
                    try (InputStream in = com.skycraft.dev.DevResources.open(Palettes.class, PATH)) {
                        if (in == null) throw new IllegalStateException("missing " + PATH);
                        r = JsonParser.parseReader(new InputStreamReader(in, StandardCharsets.UTF_8)).getAsJsonObject();
                    } catch (java.io.IOException e) {
                        throw new IllegalStateException("can't read " + PATH, e);
                    }
                    raw = r;
                }
            }
        }
        return r;
    }

    /**
     * One topographic micro-biome rule inside a regional palette. Rules are evaluated in declaration order;
     * the first matching rule wins. Omitted driver bounds default to {@code [-1e6f, 1e6f]} (or {@code [0f, 360f]}
     * for {@code aspect}).
     */
    public static final class MicroRule {
        public final String id;
        @Nullable
        public final Holder<Biome> biome;
        public final float elevLo, elevHi;
        public final float slopeLo, slopeHi;
        public final float rsLo, rsHi;
        public final float heatLo, heatHi;
        public final float waterLo, waterHi;
        public final float coastLo, coastHi;
        public final float ridgeLo, ridgeHi;
        public final float aspectLo, aspectHi;

        MicroRule(String id, @Nullable Holder<Biome> biome,
                  float elevLo, float elevHi, float slopeLo, float slopeHi,
                  float rsLo, float rsHi, float heatLo, float heatHi,
                  float waterLo, float waterHi, float coastLo, float coastHi,
                  float ridgeLo, float ridgeHi, float aspectLo, float aspectHi) {
            this.id = id;
            this.biome = biome;
            this.elevLo = elevLo;
            this.elevHi = elevHi;
            this.slopeLo = slopeLo;
            this.slopeHi = slopeHi;
            this.rsLo = rsLo;
            this.rsHi = rsHi;
            this.heatLo = heatLo;
            this.heatHi = heatHi;
            this.waterLo = waterLo;
            this.waterHi = waterHi;
            this.coastLo = coastLo;
            this.coastHi = coastHi;
            this.ridgeLo = ridgeLo;
            this.ridgeHi = ridgeHi;
            this.aspectLo = aspectLo;
            this.aspectHi = aspectHi;
        }
    }

    /** Weighted biome choices of one context. Entries are in palette order; neighbours border each other. */
    public static final class Choices {
        /** null entries stand for {@link #SURFACE}. */
        private final Holder<Biome>[] biomes;
        private final float[] upper;

        @SuppressWarnings("unchecked")
        Choices(List<Holder<Biome>> biomes, List<Integer> weights) {
            this.biomes = biomes.toArray(new Holder[0]);
            this.upper = new float[weights.size()];
            float total = 0;
            for (int w : weights) total += w;
            float acc = 0;
            for (int i = 0; i < weights.size(); i++) {
                acc += weights.get(i);
                upper[i] = acc / total;
            }
            upper[upper.length - 1] = 1.0001f;
        }

        /** The biome at climate value v in [0, 1); null means "the surface biome". */
        @Nullable
        public Holder<Biome> pick(double v) {
            for (int i = 0; i < upper.length; i++) {
                if (v < upper[i]) return biomes[i];
            }
            return biomes[biomes.length - 1];
        }

        public int size() {
            return biomes.length;
        }
    }

    /** One compiled palette: every context resolved through the fallback chain, plus ordered micro-biome rules. */
    public static final class Palette {
        public final String key;
        public final int uplandY, peakY, summitY;
        private final Choices[] contexts;
        public final MicroRule[] micro;
        /** Optional geographic bias of the climate value (see {@link #bias}); null for none. */
        @Nullable
        private final double[] linear, radial;

        Palette(String key, int uplandY, int peakY, int summitY, Choices[] contexts, MicroRule[] micro,
                @Nullable double[] linear, @Nullable double[] radial) {
            this.key = key;
            this.uplandY = uplandY;
            this.peakY = peakY;
            this.summitY = summitY;
            this.contexts = contexts;
            this.micro = micro;
            this.linear = linear;
            this.radial = radial;
        }

        public Choices get(Context context) {
            return contexts[context.ordinal()];
        }

        /**
         * Evaluates this palette's micro-biome rules at quart column {@code (qx, qz)} against {@code s}.
         * Allocation-free; returns the first matching rule in declaration order, or {@code null} if none match.
         */
        @Nullable
        public MicroRule pickMicro(int qx, int qz, MapSample s) {
            if (micro.length == 0) return null;
            float wd = s.waterDistance();
            float cd = Math.max(0f, s.coastDistance);
            float effAx = s.aspectX * s.slope + microNoise(qx, qz, 701) * 0.14f;
            float effAz = s.aspectZ * s.slope + microNoise(qx, qz, 702) * 0.14f;
            float aspectDeg = (float) Math.toDegrees(Math.atan2(effAx, -effAz));
            if (aspectDeg < 0f) aspectDeg += 360f;
            for (int k = 0; k < micro.length; k++) {
                MicroRule r = micro[k];
                float d = microNoise(qx, qz, k * 31 + 17);
                if (r.elevLo > -1e5f || r.elevHi < 1e5f) {
                    float ev = s.elevation + d * 8.0f;
                    if (ev < r.elevLo || ev > r.elevHi) continue;
                }
                if (r.slopeLo > -1e5f || r.slopeHi < 1e5f) {
                    float sv = Math.max(0f, s.slope + d * 0.035f);
                    if (sv < r.slopeLo || sv > r.slopeHi) continue;
                }
                if (r.rsLo > -1e5f || r.rsHi < 1e5f) {
                    float rv = s.rainshadow + d * 0.05f;
                    if (rv < r.rsLo || rv > r.rsHi) continue;
                }
                if (r.heatLo > -1e5f || r.heatHi < 1e5f) {
                    float hv = s.heat > 0.01f ? s.heat + d * 0.03f : 0f;
                    if (hv < r.heatLo || hv > r.heatHi) continue;
                }
                if (r.waterLo > -1e5f || r.waterHi < 1e5f) {
                    float wv = Math.max(0f, wd + d * 12.0f);
                    if (wv < r.waterLo || wv > r.waterHi) continue;
                }
                if (r.coastLo > -1e5f || r.coastHi < 1e5f) {
                    float cv = Math.max(0f, cd + d * 24.0f);
                    if (cv < r.coastLo || cv > r.coastHi) continue;
                }
                if (r.ridgeLo > -1e5f || r.ridgeHi < 1e5f) {
                    float rgv = s.ridge + d * 0.04f;
                    if (rgv < r.ridgeLo || rgv > r.ridgeHi) continue;
                }
                if (!(r.aspectLo <= 0f && r.aspectHi >= 360f)) {
                    float ad = (aspectDeg + d * 18.0f) % 360f;
                    if (ad < 0f) ad += 360f;
                    boolean ok = r.aspectLo <= r.aspectHi
                            ? (ad >= r.aspectLo && ad <= r.aspectHi)
                            : (ad >= r.aspectLo || ad <= r.aspectHi);
                    if (!ok) continue;
                }
                return r;
            }
            return null;
        }

        /**
         * The climate value v in [0, 1) shifted by position, so the choices follow the land's geography ("bias" in
         * palettes.json): linear {@code [x, z, dx, dz, span, shift]} adds shift * clamp(offset . (dx, dz) / span),
         * later entries lying towards (dx, dz); radial {@code [x, z, inner, outer, scale]} scales v down near a
         * centre, so only the first entries grow there.
         */
        public double bias(double v, int x, int z) {
            if (linear != null) {
                double t = ((x - linear[0]) * linear[2] + (z - linear[1]) * linear[3]) / linear[4];
                v += linear[5] * Math.max(-1, Math.min(1, t));
            }
            if (radial != null) {
                double d = Math.hypot(x - radial[0], z - radial[1]);
                double t = Math.max(0, Math.min(1, (d - radial[2]) / (radial[3] - radial[2])));
                v *= radial[4] + (1 - radial[4]) * t * t * (3 - 2 * t);
            }
            return Math.max(0, Math.min(0.99999, v));
        }
    }

    /** Deterministic 32-bit value hash in {@code [-1, 1]} shared with {@code tools/qa/region_audit.py}. */
    public static float hashUnit(int x, int z, int salt) {
        int h = x * 374761393 + z * 668265263 + salt * 1442695041;
        h = (h ^ (h >>> 13)) * 1274126177;
        h = h ^ (h >>> 16);
        return ((h & 0xFFFF) / 32767.5f) - 1.0f;
    }

    /** Smooth 24-block (6-quart) value noise in {@code [-1, 1]} used for micro-biome dithering and micro-aspect. */
    public static float microNoise(int qx, int qz, int salt) {
        int step = 6;
        int gx = Math.floorDiv(qx, step);
        int gz = Math.floorDiv(qz, step);
        float tx = (qx - gx * step) / (float) step;
        float tz = (qz - gz * step) / (float) step;
        tx = tx * tx * (3.0f - 2.0f * tx);
        tz = tz * tz * (3.0f - 2.0f * tz);
        float v00 = hashUnit(gx, gz, salt);
        float v10 = hashUnit(gx + 1, gz, salt);
        float v01 = hashUnit(gx, gz + 1, salt);
        float v11 = hashUnit(gx + 1, gz + 1, salt);
        return (1.0f - tz) * ((1.0f - tx) * v00 + tx * v10) + tz * ((1.0f - tx) * v01 + tx * v11);
    }

    /** All palettes compiled against one biome registry lookup. Immutable after construction. */
    public static final class Compiled {
        private final Map<String, Palette> byKey;
        /** Region palette names as given in regions.json, e.g. archetype names "frozen" for realm/frozen. */
        private final Map<String, Palette> byAlias;
        private final Palette fallback;
        public final List<Holder<Biome>> all;
        /** Every catalogue biome in order (used by the dev grid test). */
        public final List<Holder<Biome>> catalogue;

        Compiled(Map<String, Palette> byKey, Map<String, Palette> byAlias, List<Holder<Biome>> all,
                 List<Holder<Biome>> catalogue) {
            this.byKey = byKey;
            this.byAlias = byAlias;
            this.fallback = byKey.get("default");
            this.all = all;
            this.catalogue = catalogue;
        }

        @Nullable
        public Palette byKey(String key) {
            return byKey.get(key);
        }

        /** The palette of a region: by region id, then its palette name, then its province, then the default. */
        public Palette of(Region region) {
            Palette p = byKey.get(region.id());
            if (p == null && region.palette() != null) {
                p = byKey.get(region.palette());
                if (p == null) p = byAlias.get(region.palette());
            }
            if (p == null) p = byAlias.get(region.province());
            return p != null ? p : fallback;
        }

        public Collection<String> keys() {
            return byKey.keySet();
        }
    }

    /** Resolves every palette against the biome registry. Unknown biomes are skipped with a warning. */
    public static Compiled compile(HolderGetter<Biome> biomes) {
        JsonObject root = raw();
        JsonObject palettes = root.getAsJsonObject("palettes");
        Map<String, Holder<Biome>> resolved = new HashMap<>();
        Set<Holder<Biome>> all = new LinkedHashSet<>();
        List<Holder<Biome>> catalogue = new ArrayList<>();
        for (JsonElement e : root.getAsJsonArray("catalogue")) {
            Holder<Biome> h = resolve(biomes, e.getAsString(), resolved);
            if (h != null) {
                all.add(h);
                catalogue.add(h);
            }
        }
        Map<String, Palette> done = new LinkedHashMap<>();
        for (String key : palettes.keySet()) {
            compileOne(key, palettes, biomes, resolved, all, done, new LinkedHashSet<>());
        }
        Map<String, Palette> alias = new HashMap<>();
        for (Map.Entry<String, Palette> e : done.entrySet()) {
            String k = e.getKey();
            int slash = k.indexOf('/');
            if (k.startsWith("realm/") || k.startsWith("province/")) alias.put(k.substring(slash + 1), e.getValue());
        }
        return new Compiled(Map.copyOf(done), Map.copyOf(alias), List.copyOf(all), List.copyOf(catalogue));
    }

    private static Palette compileOne(String key, JsonObject palettes, HolderGetter<Biome> biomes,
                                      Map<String, Holder<Biome>> resolved, Set<Holder<Biome>> all,
                                      Map<String, Palette> done, Set<String> visiting) {
        Palette cached = done.get(key);
        if (cached != null) return cached;
        if (!visiting.add(key)) throw new IllegalStateException("palette fallback cycle at " + key);
        JsonObject p = palettes.getAsJsonObject(key);
        Palette parent = null;
        if (p.has("fallback")) parent = compileOne(p.get("fallback").getAsString(), palettes, biomes, resolved, all, done, visiting);
        JsonObject ctx = p.getAsJsonObject("contexts");
        Choices[] choices = new Choices[Context.values().length];
        for (Context c : Context.values()) {
            if (ctx.has(c.key)) {
                List<Holder<Biome>> hs = new ArrayList<>();
                List<Integer> ws = new ArrayList<>();
                for (JsonElement el : ctx.getAsJsonArray(c.key)) {
                    JsonObject o = el.getAsJsonObject();
                    String id = o.get("biome").getAsString();
                    Holder<Biome> h = SURFACE.equals(id) ? null : resolve(biomes, id, resolved);
                    if (h == null && !SURFACE.equals(id)) continue;
                    if (h != null) all.add(h);
                    hs.add(h);
                    ws.add(Math.max(1, o.get("weight").getAsInt()));
                }
                if (!hs.isEmpty()) choices[c.ordinal()] = new Choices(hs, ws);
            }
            if (choices[c.ordinal()] == null && parent != null) choices[c.ordinal()] = parent.get(c);
        }
        for (Context c : Context.values()) {
            if (choices[c.ordinal()] == null) throw new IllegalStateException("palette " + key + " has no " + c.key);
        }
        MicroRule[] micro = parent != null ? parent.micro : NO_MICRO;
        if (p.has("micro")) {
            com.google.gson.JsonArray arr = p.getAsJsonArray("micro");
            List<MicroRule> rules = new ArrayList<>(arr.size());
            for (JsonElement el : arr) {
                JsonObject ro = el.getAsJsonObject();
                String rid = ro.get("id").getAsString();
                String bid = ro.get("biome").getAsString();
                Holder<Biome> bh = SURFACE.equals(bid) ? null : resolve(biomes, bid, resolved);
                if (bh != null) all.add(bh);
                JsonObject w = ro.has("when") ? ro.getAsJsonObject("when") : new JsonObject();
                float[] elev = rangeOr(w, "elev");
                float[] slope = rangeOr(w, "slope");
                float[] rs = rangeOr(w, "rainshadow");
                float[] heat = rangeOr(w, "heat");
                float[] water = rangeOr(w, "water_dist");
                float[] coast = rangeOr(w, "coast_dist");
                float[] ridge = rangeOr(w, "ridge");
                float[] aspect = aspectOr(w);
                rules.add(new MicroRule(rid, bh,
                        elev[0], elev[1], slope[0], slope[1], rs[0], rs[1], heat[0], heat[1],
                        water[0], water[1], coast[0], coast[1], ridge[0], ridge[1], aspect[0], aspect[1]));
            }
            micro = rules.toArray(NO_MICRO);
        }
        JsonObject bias = p.has("bias") ? p.getAsJsonObject("bias") : null;
        Palette out = new Palette(key,
                intOr(p, "upland_y", parent != null ? parent.uplandY : 115),
                intOr(p, "peak_y", parent != null ? parent.peakY : 175),
                intOr(p, "summit_y", parent != null ? parent.summitY : 270), choices, micro,
                numbers(bias, "linear", 6), numbers(bias, "radial", 5));
        done.put(key, out);
        visiting.remove(key);
        return out;
    }

    private static float[] rangeOr(JsonObject w, String key) {
        if (!w.has(key)) return new float[]{-1e6f, 1e6f};
        com.google.gson.JsonArray a = w.getAsJsonArray(key);
        return new float[]{a.get(0).getAsFloat(), a.get(1).getAsFloat()};
    }

    private static float[] aspectOr(JsonObject w) {
        if (!w.has("aspect")) return new float[]{0f, 360f};
        JsonElement el = w.get("aspect");
        if (el.isJsonArray()) {
            com.google.gson.JsonArray a = el.getAsJsonArray();
            return new float[]{a.get(0).getAsFloat(), a.get(1).getAsFloat()};
        }
        return switch (el.getAsString()) {
            case "N" -> new float[]{300f, 60f};
            case "NE" -> new float[]{345f, 105f};
            case "E" -> new float[]{30f, 150f};
            case "SE" -> new float[]{75f, 195f};
            case "S" -> new float[]{120f, 240f};
            case "SW" -> new float[]{165f, 285f};
            case "W" -> new float[]{210f, 330f};
            case "NW" -> new float[]{255f, 15f};
            default -> new float[]{0f, 360f};
        };
    }

    private static int intOr(JsonObject o, String key, int def) {
        return o.has(key) ? o.get(key).getAsInt() : def;
    }

    @Nullable
    private static double[] numbers(@Nullable JsonObject o, String key, int n) {
        if (o == null || !o.has(key)) return null;
        com.google.gson.JsonArray a = o.getAsJsonArray(key);
        if (a.size() != n) throw new IllegalStateException("palette bias " + key + " needs " + n + " numbers");
        double[] out = new double[n];
        for (int i = 0; i < n; i++) out[i] = a.get(i).getAsDouble();
        return out;
    }

    @Nullable
    private static Holder<Biome> resolve(HolderGetter<Biome> biomes, String id, Map<String, Holder<Biome>> resolved) {
        if (resolved.containsKey(id)) return resolved.get(id);
        Identifier loc = Identifier.tryParse(id);
        Holder<Biome> h = loc == null ? null : biomes.get(ResourceKey.create(Registries.BIOME, loc)).orElse(null);
        if (h == null) Skycraft.LOGGER.warn("Tamriel palettes: unknown biome {}", id);
        resolved.put(id, h);
        return h;
    }
}
