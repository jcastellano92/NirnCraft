package com.skycraft.tamriel.biome;

import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import com.google.gson.JsonParser;
import com.skycraft.Skycraft;
import com.skycraft.tamriel.Region;
import net.minecraft.core.Holder;
import net.minecraft.core.HolderGetter;
import net.minecraft.core.registries.Registries;
import net.minecraft.resources.ResourceKey;
import net.minecraft.resources.ResourceLocation;
import net.minecraft.world.level.biome.Biome;
import org.jetbrains.annotations.Nullable;

import java.io.InputStream;
import java.io.InputStreamReader;
import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.Collection;
import java.util.HashMap;
import java.util.LinkedHashMap;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Map;
import java.util.Set;

/**
 * The biome palettes of Nirn ({@code skycraft/tamriel/palettes.json}, generated by tools/worldgen/biomes.py): for each
 * region (and each province, sea and realm archetype as fallbacks) the weighted biome choices of every terrain
 * context. Loaded once from the class path; {@link #compile} resolves the biome keys against a registry lookup into
 * immutable, thread-safe tables for the biome source.
 */
public final class Palettes {
    /** Terrain contexts, in the order of palettes.json's "contexts". */
    public enum Context {
        OCEAN, DEEP_OCEAN, BEACH, RIVER, LAKE, MARSH, LOWLAND, UPLAND, PEAK, SUMMIT, CAVE, DEEP_CAVE;

        public final String key = name().toLowerCase(java.util.Locale.ROOT);
    }

    public static final String SURFACE = "@surface";
    private static final String PATH = "/skycraft/tamriel/palettes.json";
    private static volatile JsonObject raw;

    private Palettes() {}

    /** The parsed palettes.json (cached). */
    public static JsonObject raw() {
        JsonObject r = raw;
        if (r == null) {
            synchronized (Palettes.class) {
                r = raw;
                if (r == null) {
                    try (InputStream in = Palettes.class.getResourceAsStream(PATH)) {
                        if (in == null) throw new IllegalStateException("missing " + PATH);
                        r = JsonParser.parseReader(new InputStreamReader(in, StandardCharsets.UTF_8)).getAsJsonObject();
                    } catch (java.io.IOException e) {
                        throw new IllegalStateException("can't read " + PATH, e);
                    }
                    raw = r;
                }
            }
        }
        return r;
    }

    /** Weighted biome choices of one context. Entries are in palette order; neighbours border each other. */
    public static final class Choices {
        /** null entries stand for {@link #SURFACE}. */
        private final Holder<Biome>[] biomes;
        private final float[] upper;

        @SuppressWarnings("unchecked")
        Choices(List<Holder<Biome>> biomes, List<Integer> weights) {
            this.biomes = biomes.toArray(new Holder[0]);
            this.upper = new float[weights.size()];
            float total = 0;
            for (int w : weights) total += w;
            float acc = 0;
            for (int i = 0; i < weights.size(); i++) {
                acc += weights.get(i);
                upper[i] = acc / total;
            }
            upper[upper.length - 1] = 1.0001f;
        }

        /** The biome at climate value v in [0, 1); null means "the surface biome". */
        @Nullable
        public Holder<Biome> pick(double v) {
            for (int i = 0; i < upper.length; i++) {
                if (v < upper[i]) return biomes[i];
            }
            return biomes[biomes.length - 1];
        }

        public int size() {
            return biomes.length;
        }
    }

    /** One compiled palette: every context resolved through the fallback chain. */
    public static final class Palette {
        public final String key;
        public final int uplandY, peakY, summitY;
        private final Choices[] contexts;

        Palette(String key, int uplandY, int peakY, int summitY, Choices[] contexts) {
            this.key = key;
            this.uplandY = uplandY;
            this.peakY = peakY;
            this.summitY = summitY;
            this.contexts = contexts;
        }

        public Choices get(Context context) {
            return contexts[context.ordinal()];
        }
    }

    /** All palettes compiled against one biome registry lookup. Immutable after construction. */
    public static final class Compiled {
        private final Map<String, Palette> byKey;
        /** Region palette names as given in regions.json, e.g. archetype names "frozen" for realm/frozen. */
        private final Map<String, Palette> byAlias;
        private final Palette fallback;
        public final List<Holder<Biome>> all;
        /** Every catalogue biome in order (used by the dev grid test). */
        public final List<Holder<Biome>> catalogue;

        Compiled(Map<String, Palette> byKey, Map<String, Palette> byAlias, List<Holder<Biome>> all,
                 List<Holder<Biome>> catalogue) {
            this.byKey = byKey;
            this.byAlias = byAlias;
            this.fallback = byKey.get("default");
            this.all = all;
            this.catalogue = catalogue;
        }

        @Nullable
        public Palette byKey(String key) {
            return byKey.get(key);
        }

        /** The palette of a region: by region id, then its palette name, then its province, then the default. */
        public Palette of(Region region) {
            Palette p = byKey.get(region.id());
            if (p == null && region.palette() != null) {
                p = byKey.get(region.palette());
                if (p == null) p = byAlias.get(region.palette());
            }
            if (p == null) p = byAlias.get(region.province());
            return p != null ? p : fallback;
        }

        public Collection<String> keys() {
            return byKey.keySet();
        }
    }

    /** Resolves every palette against the biome registry. Unknown biomes are skipped with a warning. */
    public static Compiled compile(HolderGetter<Biome> biomes) {
        JsonObject root = raw();
        JsonObject palettes = root.getAsJsonObject("palettes");
        Map<String, Holder<Biome>> resolved = new HashMap<>();
        Set<Holder<Biome>> all = new LinkedHashSet<>();
        List<Holder<Biome>> catalogue = new ArrayList<>();
        for (JsonElement e : root.getAsJsonArray("catalogue")) {
            Holder<Biome> h = resolve(biomes, e.getAsString(), resolved);
            if (h != null) {
                all.add(h);
                catalogue.add(h);
            }
        }
        Map<String, Palette> done = new LinkedHashMap<>();
        for (String key : palettes.keySet()) {
            compileOne(key, palettes, biomes, resolved, all, done, new LinkedHashSet<>());
        }
        Map<String, Palette> alias = new HashMap<>();
        for (Map.Entry<String, Palette> e : done.entrySet()) {
            String k = e.getKey();
            int slash = k.indexOf('/');
            if (k.startsWith("realm/") || k.startsWith("province/")) alias.put(k.substring(slash + 1), e.getValue());
        }
        return new Compiled(Map.copyOf(done), Map.copyOf(alias), List.copyOf(all), List.copyOf(catalogue));
    }

    private static Palette compileOne(String key, JsonObject palettes, HolderGetter<Biome> biomes,
                                      Map<String, Holder<Biome>> resolved, Set<Holder<Biome>> all,
                                      Map<String, Palette> done, Set<String> visiting) {
        Palette cached = done.get(key);
        if (cached != null) return cached;
        if (!visiting.add(key)) throw new IllegalStateException("palette fallback cycle at " + key);
        JsonObject p = palettes.getAsJsonObject(key);
        Palette parent = null;
        if (p.has("fallback")) parent = compileOne(p.get("fallback").getAsString(), palettes, biomes, resolved, all, done, visiting);
        JsonObject ctx = p.getAsJsonObject("contexts");
        Choices[] choices = new Choices[Context.values().length];
        for (Context c : Context.values()) {
            if (ctx.has(c.key)) {
                List<Holder<Biome>> hs = new ArrayList<>();
                List<Integer> ws = new ArrayList<>();
                for (JsonElement el : ctx.getAsJsonArray(c.key)) {
                    JsonObject o = el.getAsJsonObject();
                    String id = o.get("biome").getAsString();
                    Holder<Biome> h = SURFACE.equals(id) ? null : resolve(biomes, id, resolved);
                    if (h == null && !SURFACE.equals(id)) continue;
                    if (h != null) all.add(h);
                    hs.add(h);
                    ws.add(Math.max(1, o.get("weight").getAsInt()));
                }
                if (!hs.isEmpty()) choices[c.ordinal()] = new Choices(hs, ws);
            }
            if (choices[c.ordinal()] == null && parent != null) choices[c.ordinal()] = parent.get(c);
        }
        for (Context c : Context.values()) {
            if (choices[c.ordinal()] == null) throw new IllegalStateException("palette " + key + " has no " + c.key);
        }
        Palette out = new Palette(key,
                intOr(p, "upland_y", parent != null ? parent.uplandY : 115),
                intOr(p, "peak_y", parent != null ? parent.peakY : 175),
                intOr(p, "summit_y", parent != null ? parent.summitY : 270), choices);
        done.put(key, out);
        visiting.remove(key);
        return out;
    }

    private static int intOr(JsonObject o, String key, int def) {
        return o.has(key) ? o.get(key).getAsInt() : def;
    }

    @Nullable
    private static Holder<Biome> resolve(HolderGetter<Biome> biomes, String id, Map<String, Holder<Biome>> resolved) {
        if (resolved.containsKey(id)) return resolved.get(id);
        ResourceLocation loc = ResourceLocation.tryParse(id);
        Holder<Biome> h = loc == null ? null : biomes.get(ResourceKey.create(Registries.BIOME, loc)).orElse(null);
        if (h == null) Skycraft.LOGGER.warn("Tamriel palettes: unknown biome {}", id);
        resolved.put(id, h);
        return h;
    }
}
