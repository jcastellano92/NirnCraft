package com.skycraft.tamriel.biome;

import com.skycraft.Skycraft;
import com.skycraft.tamriel.biome.feature.BoulderFeature;
import com.skycraft.tamriel.biome.feature.DeadTreeFeature;
import com.skycraft.tamriel.biome.feature.DwemerPipeFeature;
import com.skycraft.tamriel.biome.feature.FallenLogFeature;
import com.skycraft.tamriel.biome.feature.GiantMushroomFeature;
import com.skycraft.tamriel.biome.feature.GrahtOakFeature;
import com.skycraft.tamriel.biome.feature.HistTreeFeature;
import com.skycraft.tamriel.biome.feature.HotSpringFeature;
import com.skycraft.tamriel.biome.feature.IceFormationFeature;
import com.skycraft.tamriel.biome.feature.LavaVentFeature;
import com.skycraft.tamriel.biome.feature.PalmTreeFeature;
import com.skycraft.tamriel.biome.feature.SpireClusterFeature;
import net.minecraft.world.level.levelgen.feature.Feature;
import net.minecraft.world.level.levelgen.feature.configurations.BlockStateConfiguration;
import net.minecraft.world.level.levelgen.feature.configurations.NoneFeatureConfiguration;
import net.minecraftforge.eventbus.api.IEventBus;
import net.minecraftforge.registries.DeferredRegister;
import net.minecraftforge.registries.ForgeRegistries;
import net.minecraftforge.registries.RegistryObject;

/**
 * Feature types of the Nirn biomes (configured and placed in data/skycraft/worldgen/.../biome/, generated by
 * tools/worldgen/biomes.py): the giant flora that vanilla tree placers can't build, and the terrain dressing.
 */
public final class BiomeFeatures {
    public static final DeferredRegister<Feature<?>> FEATURES = DeferredRegister.create(ForgeRegistries.FEATURES, Skycraft.MODID);

    public static final RegistryObject<Feature<NoneFeatureConfiguration>> GRAHT_OAK = FEATURES.register("graht_oak",
            () -> new GrahtOakFeature(NoneFeatureConfiguration.CODEC));
    public static final RegistryObject<Feature<NoneFeatureConfiguration>> HIST_TREE = FEATURES.register("hist_tree",
            () -> new HistTreeFeature(NoneFeatureConfiguration.CODEC));
    public static final RegistryObject<Feature<GiantMushroomFeature.Config>> GIANT_MUSHROOM = FEATURES.register("giant_mushroom",
            () -> new GiantMushroomFeature(GiantMushroomFeature.Config.CODEC));
    public static final RegistryObject<Feature<NoneFeatureConfiguration>> PALM_TREE = FEATURES.register("palm_tree",
            () -> new PalmTreeFeature(NoneFeatureConfiguration.CODEC));
    public static final RegistryObject<Feature<BlockStateConfiguration>> DEAD_TREE = FEATURES.register("dead_tree",
            () -> new DeadTreeFeature(BlockStateConfiguration.CODEC));
    public static final RegistryObject<Feature<BlockStateConfiguration>> FALLEN_LOG = FEATURES.register("fallen_log",
            () -> new FallenLogFeature(BlockStateConfiguration.CODEC));
    public static final RegistryObject<Feature<BoulderFeature.Config>> BOULDER = FEATURES.register("boulder",
            () -> new BoulderFeature(BoulderFeature.Config.CODEC));
    public static final RegistryObject<Feature<SpireClusterFeature.Config>> SPIRE_CLUSTER = FEATURES.register("spire_cluster",
            () -> new SpireClusterFeature(SpireClusterFeature.Config.CODEC));
    public static final RegistryObject<Feature<NoneFeatureConfiguration>> LAVA_VENT = FEATURES.register("lava_vent",
            () -> new LavaVentFeature(NoneFeatureConfiguration.CODEC));
    public static final RegistryObject<Feature<NoneFeatureConfiguration>> HOT_SPRING = FEATURES.register("hot_spring",
            () -> new HotSpringFeature(NoneFeatureConfiguration.CODEC));
    public static final RegistryObject<Feature<NoneFeatureConfiguration>> DWEMER_PIPES = FEATURES.register("dwemer_pipes",
            () -> new DwemerPipeFeature(NoneFeatureConfiguration.CODEC));
    public static final RegistryObject<Feature<NoneFeatureConfiguration>> ICE_FORMATION = FEATURES.register("ice_formation",
            () -> new IceFormationFeature(NoneFeatureConfiguration.CODEC));

    private BiomeFeatures() {}

    public static void init(IEventBus modBus) {
        FEATURES.register(modBus);
    }
}
