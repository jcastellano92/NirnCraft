package com.nirncraft.loot.container;

import com.nirncraft.inventory.BulkStore;
import com.nirncraft.inventory.ContainerOverflow;
import net.minecraft.core.registries.BuiltInRegistries;
import net.minecraft.nbt.CompoundTag;
import net.minecraft.nbt.ListTag;
import net.minecraft.nbt.Tag;
import net.minecraft.resources.Identifier;
import net.minecraft.world.item.ItemStack;
import org.jetbrains.annotations.Nullable;

import java.util.HashMap;
import java.util.List;
import java.util.Map;
import java.util.function.ToDoubleFunction;

/**
 * One player's copy of a loot container (docs/CONTAINERS.md section 4): what is inside for them, when their copy was
 * last rolled, and what that roll generated. No slots: the content is a {@link BulkStore} like every NirnCraft
 * overflow, so a container's copy is never full and never loses anything. While the player has it open, a
 * {@link LootWindow} shows the first rows in 27 slots and folds them back on close; {@link #save} merges an open
 * window's slots so a save in between loses nothing either.
 *
 * <p>Pure bookkeeping: rolling the table, the clock and the item weights come from the caller, so the rules here are
 * the same in the game and in the unit tests.</p>
 */
public final class LootInstance {
    /** {@link #rolledAt} of a copy whose table has not been rolled yet. */
    public static final long NEVER = -1L;
    public static final long DAY = 24000L;

    private final BulkStore items;
    private long rolledAt = NEVER;
    /** Weight of what the last roll generated: the base of the stash allowance (a player may always put it back). */
    private float rolledKg;
    /** Item id -> count the last roll generated; a restock waits until nothing else is inside. */
    private final Map<String, Integer> generated = new HashMap<>();
    /** The window showing this copy right now (transient). */
    @Nullable
    LootWindow window;

    public LootInstance(Runnable onChange) {
        this.items = new BulkStore(ContainerOverflow.MAX_ENTRIES, ContainerOverflow.MAX_PER_ENTRY, onChange);
    }

    public BulkStore items() {
        return items;
    }

    public long rolledAt() {
        return rolledAt;
    }

    public float rolledKg() {
        return rolledKg;
    }

    public boolean rolled() {
        return rolledAt != NEVER;
    }

    /** Test and migration hook: pretend the last roll happened at {@code at}. */
    public void backdate(long at) {
        if (rolledAt != NEVER) rolledAt = at;
    }

    // ------------------------------------------------------------------ rules

    /**
     * Whether this copy should be rolled (again) on open: never rolled, or its restock time has passed since the last
     * roll and nothing of the player's own is inside ({@code days} 0 = never restocks).
     */
    public boolean dueForRoll(long now, int days) {
        if (rolledAt == NEVER) return true;
        if (days <= 0 || now - rolledAt < days * DAY) return false;
        return !holdsForeign();
    }

    /**
     * Whether anything inside was not generated by the last roll (a kind it did not roll, or more of one than it
     * rolled): the player's own things, which a restock never touches. An unreadable row counts as the player's.
     */
    public boolean holdsForeign() {
        Map<String, Integer> left = new HashMap<>(generated);
        for (ItemStack s : contents()) {
            if (s.isEmpty()) return true;
            String id = itemId(s);
            int n = left.getOrDefault(id, 0) - s.getCount();
            if (n < 0) return true;
            left.put(id, n);
        }
        return false;
    }

    /** Replaces the content with a fresh roll at {@code now}. */
    public void restock(List<ItemStack> roll, long now, ToDoubleFunction<ItemStack> unitKg) {
        if (window != null) window.clearContent();
        items.clear();
        generated.clear();
        float kg = 0f;
        for (ItemStack s : roll) {
            if (s.isEmpty()) continue;
            generated.merge(itemId(s), s.getCount(), Integer::sum);
            kg += (float) (unitKg.applyAsDouble(s) * s.getCount());
            items.add(s.copy());
        }
        rolledKg = kg;
        rolledAt = now;
    }

    /**
     * How many of {@code stack} a player may store here now. World containers: the weight inside may grow to what the
     * last roll generated plus {@code stashKg} (so taking something and putting it back always works); weightless things
     * are limited by the entry count instead. A negative {@code stashKg} means no limit (player-placed containers).
     */
    public int room(ItemStack stack, float stashKg, ToDoubleFunction<ItemStack> unitKg) {
        if (stack.isEmpty()) return 0;
        if (stashKg < 0) return Integer.MAX_VALUE;
        double unit = unitKg.applyAsDouble(stack);
        if (unit <= 0) return entries() < generated.size() + STASH_ENTRIES || items.indexOf(stack) >= 0 ? Integer.MAX_VALUE : 0;
        double left = rolledKg + stashKg - weight(unitKg) + 0.001;
        return left <= 0 ? 0 : (int) Math.min(Integer.MAX_VALUE, Math.floor(left / unit));
    }

    /** Distinct weightless entries a world container takes on top of its roll. */
    static final int STASH_ENTRIES = 32;

    /** Everything inside: the open window's slots and the store. */
    public List<ItemStack> contents() {
        List<ItemStack> out = new java.util.ArrayList<>();
        if (window != null) {
            for (int i = 0; i < window.getContainerSize(); i++) {
                ItemStack s = window.getItem(i);
                if (!s.isEmpty()) out.add(s.copy());
            }
        }
        out.addAll(items.entries());
        return out;
    }

    public double weight(ToDoubleFunction<ItemStack> unitKg) {
        double kg = 0;
        for (ItemStack s : contents()) if (!s.isEmpty()) kg += unitKg.applyAsDouble(s) * s.getCount();
        return kg;
    }

    public int entries() {
        return items.size() + (window == null ? 0 : (int) window.getItems().stream().filter(s -> !s.isEmpty()).count());
    }

    public boolean isEmpty() {
        return contents().isEmpty();
    }

    // ------------------------------------------------------------------ persistence

    /** {@code {items: <bulk store>, rolled, kg, gen: [{id, n}]}}; an open window's slots are saved as store rows. */
    public CompoundTag save() {
        CompoundTag tag = new CompoundTag();
        BulkStore all = items;
        if (window != null && !window.isEmpty()) {
            all = BulkStore.loaded(items.save(), items.maxEntries(), items.maxPerEntry(), null);
            for (int i = 0; i < window.getContainerSize(); i++) {
                ItemStack s = window.getItem(i);
                if (!s.isEmpty()) all.add(s.copy());
            }
        }
        tag.put("items", all.save());
        tag.putLong("rolled", rolledAt);
        tag.putFloat("kg", rolledKg);
        ListTag gen = new ListTag();
        generated.forEach((id, n) -> {
            CompoundTag g = new CompoundTag();
            g.putString("id", id);
            g.putInt("n", n);
            gen.add(g);
        });
        tag.put("gen", gen);
        return tag;
    }

    public void load(CompoundTag tag) {
        items.load(tag.getCompoundOrEmpty("items"));
        rolledAt = tag.getLongOr("rolled", NEVER);
        rolledKg = tag.getFloatOr("kg", 0f);
        generated.clear();
        for (Tag t : tag.getListOrEmpty("gen")) {
            if (t instanceof CompoundTag g) generated.merge(g.getStringOr("id", ""), g.getIntOr("n", 0), Integer::sum);
        }
    }

    static String itemId(ItemStack s) {
        Identifier id = BuiltInRegistries.ITEM.getKey(s.getItem());
        return id == null ? "" : id.toString();
    }
}
