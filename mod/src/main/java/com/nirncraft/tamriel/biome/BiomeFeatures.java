package com.nirncraft.tamriel.biome;

import com.nirncraft.NirnCraft;
import com.nirncraft.tamriel.biome.feature.BoulderFeature;
import com.nirncraft.tamriel.biome.feature.DeadTreeFeature;
import com.nirncraft.tamriel.biome.feature.DwemerPipeFeature;
import com.nirncraft.tamriel.biome.feature.FallenLogFeature;
import com.nirncraft.tamriel.biome.feature.GiantMushroomFeature;
import com.nirncraft.tamriel.biome.feature.GrahtOakFeature;
import com.nirncraft.tamriel.biome.feature.HistTreeFeature;
import com.nirncraft.tamriel.biome.feature.HotSpringFeature;
import com.nirncraft.tamriel.biome.feature.IceFormationFeature;
import com.nirncraft.tamriel.biome.feature.LavaVentFeature;
import com.nirncraft.tamriel.biome.feature.PalmTreeFeature;
import com.nirncraft.tamriel.biome.feature.SpireClusterFeature;
import net.minecraft.world.level.levelgen.feature.Feature;
import com.mojang.serialization.MapCodec;
import com.nirncraft.worldgen.BlockStateConfiguration;
import com.nirncraft.worldgen.NoneFeatureConfiguration;
import net.neoforged.bus.api.IEventBus;
import net.neoforged.neoforge.registries.DeferredRegister;
import net.minecraft.core.registries.BuiltInRegistries;
import net.minecraft.core.registries.Registries;
import java.util.function.Supplier;

/**
 * Feature types of the Nirn biomes (configured and placed in data/nirncraft/worldgen/.../biome/, generated by
 * tools/worldgen/biomes.py): the giant flora that vanilla tree placers can't build, and the terrain dressing.
 */
public final class BiomeFeatures {
    public static final DeferredRegister<MapCodec<? extends Feature>> FEATURES = DeferredRegister.create(Registries.FEATURE_TYPE, NirnCraft.MODID);

    public static final Supplier<MapCodec<? extends Feature>> GRAHT_OAK = FEATURES.register("graht_oak",
            () -> new GrahtOakFeature(NoneFeatureConfiguration.CODEC).codec());
    public static final Supplier<MapCodec<? extends Feature>> HIST_TREE = FEATURES.register("hist_tree",
            () -> new HistTreeFeature(NoneFeatureConfiguration.CODEC).codec());
    public static final Supplier<MapCodec<? extends Feature>> GIANT_MUSHROOM = FEATURES.register("giant_mushroom",
            () -> new GiantMushroomFeature(GiantMushroomFeature.Config.CODEC).codec());
    public static final Supplier<MapCodec<? extends Feature>> PALM_TREE = FEATURES.register("palm_tree",
            () -> new PalmTreeFeature(NoneFeatureConfiguration.CODEC).codec());
    public static final Supplier<MapCodec<? extends Feature>> DEAD_TREE = FEATURES.register("dead_tree",
            () -> new DeadTreeFeature(BlockStateConfiguration.CODEC).codec());
    public static final Supplier<MapCodec<? extends Feature>> FALLEN_LOG = FEATURES.register("fallen_log",
            () -> new FallenLogFeature(BlockStateConfiguration.CODEC).codec());
    public static final Supplier<MapCodec<? extends Feature>> BOULDER = FEATURES.register("boulder",
            () -> new BoulderFeature(BoulderFeature.Config.CODEC).codec());
    public static final Supplier<MapCodec<? extends Feature>> SPIRE_CLUSTER = FEATURES.register("spire_cluster",
            () -> new SpireClusterFeature(SpireClusterFeature.Config.CODEC).codec());
    public static final Supplier<MapCodec<? extends Feature>> LAVA_VENT = FEATURES.register("lava_vent",
            () -> new LavaVentFeature(NoneFeatureConfiguration.CODEC).codec());
    public static final Supplier<MapCodec<? extends Feature>> HOT_SPRING = FEATURES.register("hot_spring",
            () -> new HotSpringFeature(NoneFeatureConfiguration.CODEC).codec());
    public static final Supplier<MapCodec<? extends Feature>> DWEMER_PIPES = FEATURES.register("dwemer_pipes",
            () -> new DwemerPipeFeature(NoneFeatureConfiguration.CODEC).codec());
    public static final Supplier<MapCodec<? extends Feature>> ICE_FORMATION = FEATURES.register("ice_formation",
            () -> new IceFormationFeature(NoneFeatureConfiguration.CODEC).codec());

    private BiomeFeatures() {}

    public static void init(IEventBus modBus) {
        FEATURES.register(modBus);
    }
}
