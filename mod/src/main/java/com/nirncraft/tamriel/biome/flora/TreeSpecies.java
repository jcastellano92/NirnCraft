    private static void add(Map<String, TreeSpecies> m, String name, Shape shape, Consumer<TreeSpecies> setup) {
        TreeSpecies s = new TreeSpecies(name, shape);
        setup.accept(s);
        if (s.leaves == null) s.leaves = Blocks.OAK_LEAVES.defaultBlockState();
        if (s.log == null) s.log = Blocks.OAK_LOG.defaultBlockState();
        m.put(name, s);
    }

