package com.nirncraft.tamriel;

import com.mojang.serialization.MapCodec;
import com.mojang.serialization.Codec;
import com.nirncraft.NirnCraft;
import com.nirncraft.tamriel.biome.BiomeBlocks;
import com.nirncraft.tamriel.biome.BiomeFeatures;
import net.minecraft.core.registries.Registries;
import net.minecraft.world.level.biome.BiomeSource;
import net.neoforged.bus.api.IEventBus;
import net.neoforged.neoforge.registries.DeferredRegister;
import java.util.function.Supplier;

/**
 * Biomes: the nirncraft:tamriel biome source, biome blocks, trees and vegetation features (Phase 2 workstream B).
 * The biomes themselves, their features, tags, palettes and the surface rule are generated by
 * tools/worldgen/biomes.py; see docs/TAMRIEL.md section 5.
 */
public final class TamrielBiomes {
    public static final DeferredRegister<MapCodec<? extends BiomeSource>> BIOME_SOURCES =
            DeferredRegister.create(Registries.BIOME_SOURCE, NirnCraft.MODID);

    public static final Supplier<MapCodec<? extends BiomeSource>> TAMRIEL_SOURCE =
            BIOME_SOURCES.register("tamriel", () -> TamrielBiomeSource.CODEC);

    private TamrielBiomes() {}

    public static void init(IEventBus modBus) {
        BIOME_SOURCES.register(modBus);
        BiomeBlocks.init(modBus);
        BiomeFeatures.init(modBus);
        com.nirncraft.tamriel.biome.flora.Flora.init(modBus);
    }
}
