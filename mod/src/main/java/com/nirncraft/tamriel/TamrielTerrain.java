package com.nirncraft.tamriel;

import com.mojang.serialization.Codec;
import com.nirncraft.NirnCraft;
import com.nirncraft.tamriel.terrain.MapWaterFeature;
import com.nirncraft.tamriel.terrain.TamrielChannel;
import com.nirncraft.tamriel.terrain.TamrielDevCommands;
import com.nirncraft.tamriel.terrain.TamrielHeight;
import com.nirncraft.tamriel.terrain.TamrielSpawn;
import net.minecraft.core.registries.Registries;
import net.minecraft.world.level.levelgen.densityfunction.DensityFunction;
import net.minecraft.world.level.levelgen.feature.Feature;
import com.mojang.serialization.MapCodec;
import com.nirncraft.worldgen.NoneFeatureConfiguration;
import net.neoforged.neoforge.common.NeoForge;
import net.neoforged.bus.api.IEventBus;
import net.neoforged.neoforge.registries.DeferredRegister;
import java.util.function.Supplier;

/**
 * Terrain (Phase 2 workstream T): the density function types and the map water feature used by the
 * {@code nirncraft:tamriel} noise settings, the Helgen world spawn, and the {@code /nirncraft-tamriel} dev commands.
 * The JSON side (noise settings, density functions, world presets) is generated by
 * {@code tools/worldgen/noise_settings.py}.
 */
public final class TamrielTerrain {
    public static final DeferredRegister<MapCodec<? extends DensityFunction>> DENSITY_TYPES =
            DeferredRegister.create(Registries.DENSITY_FUNCTION_TYPE, NirnCraft.MODID);
    public static final DeferredRegister<MapCodec<? extends Feature>> FEATURES = DeferredRegister.create(Registries.FEATURE_TYPE, NirnCraft.MODID);

    public static final Supplier<MapCodec<? extends DensityFunction>> CHANNEL =
            DENSITY_TYPES.register("tamriel_channel", () -> TamrielChannel.CODEC);
    public static final Supplier<MapCodec<? extends DensityFunction>> HEIGHT =
            DENSITY_TYPES.register("tamriel_height", () -> TamrielHeight.CODEC);
    public static final Supplier<MapCodec<? extends Feature>> MAP_WATER =
            FEATURES.register("map_water", () -> new MapWaterFeature(NoneFeatureConfiguration.CODEC).codec());
    public static final Supplier<MapCodec<? extends Feature>> RANDOM_PATCH =
            FEATURES.register("random_patch", () -> new com.nirncraft.worldgen.RandomPatchFeature().codec());

    private TamrielTerrain() {}

    public static void init(IEventBus modBus) {
        DENSITY_TYPES.register(modBus);
        FEATURES.register(modBus);
        NeoForge.EVENT_BUS.addListener(TamrielSpawn::onCreateSpawn);
        NeoForge.EVENT_BUS.addListener(TamrielDevCommands::register);
        com.nirncraft.qa.Tour.init();  // the host's camera tour (/nirncraft-tour)
        com.nirncraft.qa.QaCommands.init();  // the harness online sampling (/nirncraft-qa)
    }
}
