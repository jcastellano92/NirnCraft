package com.nirncraft.dungeons.qa;

import java.io.BufferedWriter;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.Set;
import java.util.TreeMap;

/** Similarity between dungeons of a theme, and the CSV and Markdown reports of a run. */
final class QaReport {
    private QaReport() {}

    /** Nearest-neighbour Jaccard similarity of each dungeon's layout and content signatures within its theme. */
    static void similarity(List<QaDungeon> done) {
        Map<String, List<QaDungeon>> groups = DungeonQa.byTheme(done);
        for (List<QaDungeon> g : groups.values()) {
            for (QaDungeon a : g) {
                double bestL = 0, bestC = 0;
                for (QaDungeon b : g) {
                    if (a == b) continue;
                    bestL = Math.max(bestL, jaccard(a.layoutSig, b.layoutSig));
                    bestC = Math.max(bestC, jaccard(a.contentSig, b.contentSig));
                }
                a.m.put("sim_layout", QaDungeon.round2(bestL));
                a.m.put("sim_content", QaDungeon.round2(bestC));
            }
        }
    }

    static double jaccard(Set<String> a, Set<String> b) {
        if (a.isEmpty() && b.isEmpty()) return 1;
        int inter = 0;
        for (String s : a) if (b.contains(s)) inter++;
        return inter / (double) (a.size() + b.size() - inter);
    }

    static List<String> columns(List<QaDungeon> done) {
        Set<String> cols = new LinkedHashSet<>();
        for (QaDungeon d : done) cols.addAll(d.m.keySet());
        return new ArrayList<>(cols);
    }

    static void csv(List<QaDungeon> done, Path file) throws IOException {
        List<String> cols = columns(done);
        try (BufferedWriter w = Files.newBufferedWriter(file, StandardCharsets.UTF_8)) {
            w.write("label,category,structure,x,z");
            for (String c : cols) w.write("," + c);
            w.write(",blockers,warnings\n");
            for (QaDungeon d : done) {
                QaSample s = d.sample;
                w.write(String.join(",", esc(s.label()), s.category(), s.structureId().toString(), String.valueOf(s.x()), String.valueOf(s.z())));
                for (String c : cols) w.write("," + esc(String.valueOf(d.m.getOrDefault(c, ""))));
                w.write("," + esc(String.join("; ", d.blockers)) + "," + esc(String.join("; ", d.warnings)) + "\n");
            }
        }
    }

    private static String esc(String s) {
        if (s.contains(",") || s.contains("\"") || s.contains("\n")) return "\"" + s.replace("\"", "\"\"") + "\"";
        return s;
    }

    static double num(QaDungeon d, String key) {
        Object o = d.m.get(key);
        if (o instanceof Number n) return n.doubleValue();
        try {
            return o == null ? Double.NaN : Double.parseDouble(o.toString());
        } catch (NumberFormatException e) {
            return Double.NaN;
        }
    }

    static double mean(List<QaDungeon> g, String key) {
        double s = 0;
        int n = 0;
        for (QaDungeon d : g) {
            double v = num(d, key);
            if (Double.isNaN(v) || v < 0 && !key.equals("ramp")) continue;
            s += v;
            n++;
        }
        return n == 0 ? Double.NaN : s / n;
    }

    static double pct(List<QaDungeon> g, String key) {
        int n = 0, yes = 0;
        for (QaDungeon d : g) {
            double v = num(d, key);
            if (Double.isNaN(v)) continue;
            n++;
            if (v > 0) yes++;
        }
        return n == 0 ? Double.NaN : 100.0 * yes / n;
    }

    private static String f(double v) {
        if (Double.isNaN(v)) return "-";
        return Math.abs(v) >= 100 ? String.format(Locale.ROOT, "%.0f", v) : String.format(Locale.ROOT, "%.1f", v);
    }

    static void markdown(List<QaDungeon> done, List<String> failed, String tag, long seconds, Path file) throws IOException {
        Map<String, List<QaDungeon>> groups = DungeonQa.byTheme(done);
        int blockers = 0;
        for (QaDungeon d : done) blockers += d.blockers.size();
        try (BufferedWriter w = Files.newBufferedWriter(file, StandardCharsets.UTF_8)) {
            w.write("# Dungeon QA report: " + tag + "\n\n");
            w.write(String.format(Locale.ROOT, "%d dungeons analysed (%d named, %d random) in %d s; %d failed to start; **%d blockers**.%n%n",
                    done.size(), done.stream().filter(d -> "named".equals(d.sample.category())).count(),
                    done.stream().filter(d -> "random".equals(d.sample.category())).count(), seconds, failed.size(), blockers));
            w.write("Generated by `/nirncraft-dungeon-qa run` (dungeons.qa). Each dungeon is planned through its structure's own "
                    + "`findGenerationPoint`, painted into an in-memory level over the sampled terrain and walked by the bot: it "
                    + "enters from the surface, takes claws from reachable containers, solves glyph pillars from their tablets and "
                    + "pulls levers. Columns are explained in docs/DUNGEONS.md.\n\n");

            w.write("## Per theme (means)\n\n");
            String[][] cols = {
                    {"n", ""}, {"blockers", ""}, {"rooms", "rooms"}, {"reached %", ""}, {"path", "path_blocks"}, {"walk s", "walk_seconds"},
                    {"vert", "path_vertical"}, {"floors", "floor_levels"}, {"enemies", "enemies"}, {"on path", "enemies_on_path"},
                    {"ramp", "ramp"}, {"boss %", "boss_present"}, {"boss x", "boss_ratio"}, {"traps", "traps"}, {"dark %", "dark_pct"},
                    {"light", "mean_light"}, {"loot", "loot_total"}, {"boss loot", "loot_boss"}, {"side rwd %", "side_rewards"},
                    {"loop %", "loop_back"}, {"cycles", "cycles"}, {"window %", "foreshadow"}, {"empty DE", "dead_ends_empty"},
                    {"notes", "notes"}, {"setpc", "setpiece_rooms"}, {"sim L", "sim_layout"},
                    {"sim C", "sim_content"}, {"design", "design_score"}};
            w.write("| theme |");
            for (String[] c : cols) w.write(" " + c[0] + " |");
            w.write("\n|---|");
            for (int i = 0; i < cols.length; i++) w.write("---:|");
            w.write("\n");
            List<QaDungeon> everything = new ArrayList<>(done);
            Map<String, List<QaDungeon>> rows = new LinkedHashMap<>(groups);
            rows.put("**all**", everything);
            for (Map.Entry<String, List<QaDungeon>> e : rows.entrySet()) {
                List<QaDungeon> g = e.getValue();
                w.write("| " + e.getKey() + " |");
                for (String[] c : cols) {
                    String v = switch (c[0]) {
                        case "n" -> String.valueOf(g.size());
                        case "blockers" -> String.valueOf(g.stream().mapToInt(d -> d.blockers.size()).sum());
                        case "reached %" -> f(100.0 * g.stream().mapToDouble(d -> num(d, "rooms_reached")).sum()
                                / Math.max(1, g.stream().mapToDouble(d -> num(d, "rooms")).sum()));
                        case "boss %", "loop %", "side rwd %", "window %" -> f(pct(g, c[1]));
                        default -> f(mean(g, c[1]));
                    };
                    w.write(" " + v + " |");
                }
                w.write("\n");
            }

            w.write("\n## Blockers\n\n");
            if (blockers == 0) w.write("None.\n");
            for (QaDungeon d : done) {
                for (String b : d.blockers) w.write("- `" + d.sample.label() + "` (" + d.m.get("theme") + ", " + d.sample.x() + " " + d.sample.z() + "): " + b + "\n");
            }
            if (!failed.isEmpty()) {
                w.write("\n## Did not start\n\n");
                for (String s : failed) w.write("- " + s + "\n");
            }

            w.write("\n## Warnings (most common)\n\n");
            Map<String, Integer> warn = new TreeMap<>();
            for (QaDungeon d : done) for (String s : d.warnings) warn.merge(s.replaceAll("-?\\d+", "#"), 1, Integer::sum);
            warn.entrySet().stream().sorted((a, b) -> b.getValue() - a.getValue()).limit(25)
                    .forEach(e -> write(w, "- " + e.getValue() + " x " + e.getKey() + "\n"));

            w.write("\n## Design checklist gaps (medium+ dungeons)\n\n");
            Map<String, Integer> gaps = new TreeMap<>();
            int medium = 0;
            for (QaDungeon d : done) {
                if (num(d, "rooms") < 5) continue;
                medium++;
                String miss = String.valueOf(d.m.getOrDefault("design_missing", ""));
                for (String s : miss.split(" ")) if (!s.isBlank()) gaps.merge(s, 1, Integer::sum);
            }
            w.write(medium + " dungeons with 5+ rooms.\n\n| missing | dungeons |\n|---|---:|\n");
            int fm = medium;
            gaps.forEach((k, v) -> write(w, "| " + k + " | " + v + " (" + f(100.0 * v / Math.max(1, fm)) + "%) |\n"));

            w.write("\n## Niches (path length / verticality / puzzle): distinct niches filled per theme\n\n");
            for (Map.Entry<String, List<QaDungeon>> e : groups.entrySet()) {
                Map<String, Integer> bins = new TreeMap<>();
                for (QaDungeon d : e.getValue()) bins.merge(String.valueOf(d.m.getOrDefault("niche", "?")), 1, Integer::sum);
                w.write("- " + e.getKey() + ": " + bins.size() + " niches " + bins + "\n");
            }

            w.write("\n## Set pieces seen\n\n");
            Map<String, Integer> sp = new TreeMap<>();
            for (QaDungeon d : done) {
                for (String s : String.valueOf(d.m.getOrDefault("set_pieces", "")).split("\\|")) if (!s.isBlank()) sp.merge(d.m.get("theme") + ": " + s, 1, Integer::sum);
            }
            sp.forEach((k, v) -> write(w, "- " + k + " (" + v + ")\n"));

            w.write("\n## Named dungeons\n\n| place | theme | rooms | path | walk s | enemies | boss | loot | boss loot | dark % | loop | design | blockers |\n"
                    + "|---|---|---:|---:|---:|---:|---|---:|---:|---:|---:|---:|---|\n");
            for (QaDungeon d : done) {
                if (!"named".equals(d.sample.category())) continue;
                w.write(String.format(Locale.ROOT, "| %s | %s | %s | %s | %s | %s | %s | %s | %s | %s | %s | %s | %s |%n", d.sample.label(),
                        d.m.get("theme"), d.m.get("rooms"), d.m.get("path_blocks"), d.m.get("walk_seconds"), d.m.get("enemies"),
                        String.valueOf(d.m.getOrDefault("boss", "")).replace("|", "/"), d.m.get("loot_total"), d.m.get("loot_boss"),
                        d.m.get("dark_pct"), d.m.get("loop_back"), d.m.get("design_score"), d.blockers.isEmpty() ? "" : String.valueOf(d.blockers.size())));
            }
        }
    }

    private static void write(BufferedWriter w, String s) {
        try {
            w.write(s);
        } catch (IOException e) {
            throw new java.io.UncheckedIOException(e);
        }
    }
}
