    private static void tourSpotTick(Minecraft mc, String[] spots) {
        int i = spotIndex;
        if (i >= spots.length) {
            NirnCraft.LOGGER.info("=== NirnCraft Autotest: tour finished. Closing client. ===");
            mc.stop();
            return;
        }
        String[] p = spots[i].split(":");
        int x = Integer.parseInt(p[1].trim()), z = Integer.parseInt(p[2].trim());
        float yaw = p.length > 3 ? Float.parseFloat(p[3].trim()) : 0f;
        String weather = p.length > 4 ? p[4].trim() : "clear";
        float groundPitch = p.length > 5 ? Float.parseFloat(p[5].trim()) : 8f;
        String tag = String.format(java.util.Locale.ROOT, "t%02d_%s", i + 2, p[0].trim());
        String last = TOUR_FAR > 0 ? "_far" : "_air";
        switch (spotPhase++) {
            case 0 -> {
                if (p.length > 6) serverCommand(mc, "time set " + Math.floorMod(Long.parseLong(p[6].trim()), 24000L));
                tourTeleport(mc, x, z, 3, yaw, groundPitch, weather);
                tourWait = TOUR_WAIT;
            }
            case 1 -> {
                tourTeleport(mc, x, z, 2, yaw, groundPitch, weather);
                com.nirncraft.atmosphere.client.ClientWeather.snapForTest();
                resetFps();
                tourWait = 60;
            }
            case 2 -> {
                captureAndSave(mc, tag + "_ground");
                logPerf(mc, tag + "_ground");
                tourTeleport(mc, x, z, TOUR_UP, yaw, TOUR_PITCH, weather);
                com.nirncraft.atmosphere.client.ClientWeather.snapForTest();
                tourWait = TOUR_WAIT * 3 / 4;
                resetFps();
            }
            case 3 -> {
                captureAndSave(mc, tag + "_air");
                logPerf(mc, tag + "_air");
                if (TOUR_FAR > 0) {
                    tourTeleport(mc, x, z, TOUR_FAR, yaw, 6f, weather);
                    tourWait = TOUR_WAIT / 2;
                    resetFps();
                }
            }
            case 4 -> {
                if (TOUR_FAR > 0) {
                    captureAndSave(mc, tag + "_far");
                    logPerf(mc, tag + "_far");
                }
                spotShadersToggled = SHADER_TOGGLE && irisShaders();
                if (spotShadersToggled) {
                    setIrisShaders(false);
                    tourWait = 160;
                    resetFps();
                }
            }
            case 5 -> {
                if (spotShadersToggled) {
                    captureAndSave(mc, tag + last + "_noshaders");
                    logPerf(mc, tag + last + "_noshaders");
                    setIrisShaders(true);
                    tourWait = 200;
                }
            }
            default -> {
                spotIndex++;
                spotPhase = 0;
                tourWait = 0;
            }
        }
    }

    /**
     * Optional {@code -Dnirncraft.autotest.commands=cmd,cmd,...} ('+' for spaces; '@p' is the player): run each server
     * command (as the player, spectating) and screenshot what it shows, e.g. the dungeon analyzer's
     * {@code nirncraft-dungeon-qa view <place> boss} to look at a dungeon's set pieces.
     */
    private static final String COMMANDS = System.getProperty("nirncraft.autotest.commands", "");
    private static int commandStep;

    private static void commandTick(Minecraft mc) {
        if (tourWait-- > 0) return;
        String[] cmds = COMMANDS.split(",");
        int s = commandStep++;
        tourWait = 40;
        if (s == 0) {
            com.nirncraft.network.SkyNetwork.sendToServer(new com.nirncraft.network.CorePackets.ChooseRace(com.nirncraft.core.Race.NORD.id()));
            mc.gui.setScreen(null);
            serverCommand(mc, "gamerule advance_time false");
            serverCommand(mc, "gamerule spawn_mobs false");
            serverCommand(mc, "time set 6000");
            serverCommand(mc, "gamemode spectator @p");
            tourWait = 60;
            return;
        }
        int i = (s - 1) / 2;
        if (i >= cmds.length) {
            NirnCraft.LOGGER.info("=== NirnCraft Autotest: command tour finished. Closing client. ===");
            mc.stop();
            return;
        }
        String cmd = cmds[i].trim().replace('+', ' ');
        // no pause menu (a window without focus opens it and stops the integrated server), no HUD or chat in the shot
        mc.gui.setScreen(null);
        com.nirncraft.client.autotest.ReviewWorlds.hudHidden(mc, true);
        if ((s - 1) % 2 == 0) {
            serverCommand(mc, "execute as @p at @p run " + cmd);
            tourWait = TOUR_WAIT;
        } else {
            String[] w = cmd.split(" ");
            String tag = w.length >= 3 ? w[w.length - 2] + "_" + w[w.length - 1] : "shot";
            captureAndSave(mc, String.format(java.util.Locale.ROOT, "c%02d_%s", i, tag.replaceAll("[^a-z0-9_]", "")));
        }
    }

    @SubscribeEvent
    public static void onClientTick(net.neoforged.neoforge.client.event.ClientTickEvent.Post event) {
        if(ReviewCaptures.pending()>0 && !LIVE)return;
        if (!ENABLED) return;
        Minecraft mc = Minecraft.getInstance();
        if (KEEP_WORLD && mc.gui.screen() instanceof net.minecraft.client.gui.screens.BackupConfirmScreen) {
            // the kept test world's first load: accept its experimental settings for the test (NeoForge remembers it)
            UiProbe.click(mc, net.minecraft.locale.Language.getInstance().getOrDefault("selectWorld.backupJoinSkipButton"));
            NirnCraft.LOGGER.info("Autotest: accepted the experimental-settings prompt for the kept test world");
            return;
        }
        if (LIVE) worldReadyHook(mc);
        if (LIVE && mc.level == null) noWorldHeartbeat(mc);
        if (mc.level == null && !AUTO_SERVER.isEmpty()) {
            // Keep failed TCP diagnostics on their real connection screen; never fall back to an integrated world.
            if (!autoServerStarted && (mc.gui.screen() instanceof net.minecraft.client.gui.screens.TitleScreen
                    || mc.gui.screen() instanceof com.nirncraft.client.screen.title.SkyTitleScreen)) {
                autoServerStarted = true;
                try { QaTransport.connect(mc, mc.gui.screen(), AUTO_SERVER); }
                catch (RuntimeException failure) { NirnCraft.LOGGER.error("Autotest: could not connect to loopback QA server {}", AUTO_SERVER, failure); }
            }
            return;
        }
        if (mc.level == null && CREATE_FLOW) {
            createFlowTick(mc);
            return;
        }
        if (mc.level == null && !AUTO_WORLD.isEmpty() && !autoWorldStarted
                && (mc.gui.screen() instanceof net.minecraft.client.gui.screens.TitleScreen
                || mc.gui.screen() instanceof com.nirncraft.client.screen.title.SkyTitleScreen)) {
            openAutoWorld(mc);
            return;
        }
        if (mc.level == null || mc.player == null) return;

        tick++;
        if (!worldReady) {
            if (tick > 100) { // wait ~5 seconds for world generation and client settling
                worldReady = true;
                tick = 0;
                step = 0;
                try {
                    Files.createDirectories(SCREENSHOT_DIR);
                } catch (Exception ignored) {}
                NirnCraft.LOGGER.info("=== NirnCraft Autotest: World loaded, beginning test suite ===");
            }
            return;
        }
        if (LIVE) {
            sampleFps(mc);
            liveTick(mc);
            return;
        }
        if (!TOUR.isEmpty()) {
            sampleFps(mc);
            tourTick(mc);
            return;
        }
        if (com.nirncraft.guide.client.GuideAutotest.ENABLED) { // -Dnirncraft.autotest.guide=true: the handbook and hints
            com.nirncraft.guide.client.GuideAutotest.tick(mc);
            return;
        }
        if (MountsAutotest.ENABLED) {
            MountsAutotest.tick(mc);
            return;
        }
        if (com.nirncraft.lore.place.client.PlaceLoreAutotest.ENABLED) { // -Dnirncraft.autotest.placelore=<place>: its notes
            com.nirncraft.lore.place.client.PlaceLoreAutotest.tick(mc);
            return;
        }
        if (!COMMANDS.isEmpty()) {
            commandTick(mc);
            return;
        }

        // Run steps with pauses between to let renderers stabilize and draw
        if (tick % 40 == 0) {
            runStep(mc, step++);
        }
    }

