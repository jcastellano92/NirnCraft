    /** With {@link #CREATE_FLOW}: {@code -Dnirncraft.autotest.load=<save folder>} loads that save instead of creating one. */
    private static final String LOAD_WORLD = System.getProperty("nirncraft.autotest.load", "");
    private static int createTicks;
    private static int createStage;
    private static final java.util.Set<String> SEEN_PROMPTS = new java.util.HashSet<>();

    private static void createFlowTick(Minecraft mc) {
        createTicks++;
        net.minecraft.client.gui.screens.Screen s = mc.gui.screen();
        if (s instanceof net.minecraft.client.gui.screens.AccessibilityOnboardingScreen) {
            mc.gui.setScreen(new net.minecraft.client.gui.screens.TitleScreen());
            return;
        }
        if (createStage == 0 && (s instanceof net.minecraft.client.gui.screens.TitleScreen
                || s instanceof com.nirncraft.client.screen.title.SkyTitleScreen) && createTicks > 40) {
            createStage = 1;
            createTicks = 0;
            try {
                Files.createDirectories(SCREENSHOT_DIR);
            } catch (Exception ignored) {}
            if (!LOAD_WORLD.isEmpty()) {
                // Continue an existing save, as the title screen's Continue does
                NirnCraft.LOGGER.info("Autotest: loading saved world {}", LOAD_WORLD);
                createStage = 2;
                ReviewWorlds.open(mc,LOAD_WORLD,s);
                return;
            }
            NirnCraft.LOGGER.info("Autotest: New Game from the title screen ({})", s.getClass().getSimpleName());
            net.minecraft.client.gui.screens.worldselection.CreateWorldScreen.openFresh(mc,()->mc.gui.setScreen(s));
        } else if (createStage == 1 && s instanceof com.nirncraft.client.screen.title.SkyCreateWorldScreen && createTicks > 40) {
            createStage = 2;
            createTicks = 0;
            captureAndSave(mc, "00_create_world_screen");
            s.keyPressed(new net.minecraft.client.input.KeyEvent(com.mojang.blaze3d.platform.InputConstants.KEY_RETURN,0,0));
        } else if (createStage >= 2) {
            String name = s == null ? "none" : s.getClass().getName();
            if (!name.equals(lastScreen)) {
                lastScreen = name;
                createTicks = 0;
                NirnCraft.LOGGER.info("Autotest: world creation shows {} \"{}\"", name, s == null ? "" : s.getTitle().getString());
            } else if (createTicks == 60 && s != null && SEEN_PROMPTS.add(name)) {
                // a screen that stays up for 3 s during creation is a prompt or a hang a player would see
                NirnCraft.LOGGER.warn("Autotest: world creation waits at {} \"{}\"", name, s.getTitle().getString());
                captureAndSave(mc, "00_create_world_wait_" + SEEN_PROMPTS.size());
            }
        }
    }

