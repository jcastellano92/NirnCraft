    /**
     * Teleports the player to (x, surface + up, z) on the server thread: the generator's estimate before the chunk
     * exists, the real height (above trees) once it is loaded. Sets the requested regional weather there.
     */
    private static void tourTeleport(Minecraft mc, int x, int z, int up, float yaw, float pitch, String weather) {
        var server = mc.getSingleplayerServer();
        if (server == null || mc.player == null) return;
        String name = mc.player.getGameProfile().name();
        String wKind = (weather == null || weather.isBlank()) ? "clear" : weather.trim();
        server.execute(() -> {
            var level = server.overworld();
            boolean loaded = level.getChunkSource().hasChunk(x >> 4, z >> 4);
            int h = loaded ? level.getHeight(net.minecraft.world.level.levelgen.Heightmap.Types.MOTION_BLOCKING, x, z)
                    : level.getChunkSource().getGenerator().getBaseHeight(x, z,
                    net.minecraft.world.level.levelgen.Heightmap.Types.WORLD_SURFACE_WG, level, level.getChunkSource().randomState());
            server.getCommands().performPrefixedCommand(server.createCommandSourceStack(),
                    String.format(java.util.Locale.ROOT, "tp %s %d %d %d %.0f %.0f", name, x, h + up, z, yaw, pitch));
            server.getCommands().performPrefixedCommand(server.createCommandSourceStack().withSuppressedOutput(),
                    "execute as " + name + " at " + name + " run nirncraft-weather set " + wKind + " 120");
            // Optional controlled front for visual regressions: natural fronts can override a regional spell.
            if (Boolean.getBoolean("nirncraft.autotest.tourFront")) {
                var kind = com.nirncraft.atmosphere.weather.WeatherKind.byId(wKind);
                if (kind != null) com.nirncraft.atmosphere.weather.RegionalWeather.addFront(server,
                        new com.nirncraft.atmosphere.WeatherFront(1_000_000, x, z, 2200f, 0f, 0f, kind, 1f, 12000));
            }
            NirnCraft.LOGGER.info("Autotest tour: {} at {} {} {} (surface {}, {}, weather={})", name, x, h + up, z, h, loaded ? "loaded" : "estimate", wKind);
        });
    }

