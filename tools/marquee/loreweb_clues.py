#!/usr/bin/env python3
"""Extract the placeable clues of the lore web for the scene plan (pipeline P6).

Reads tools/marquee/loreweb.json (situations: three environmental clues per place plus a thread clue) and the place
lore resource (which places have a readable "web"/"thread" note), and writes
mod/src/main/resources/skycraft/scatter/loreweb_clues.json, an input of the baked scene plan
(com.skycraft.worldplan.scene.ScenePlanBuilder). Re-run after loreweb_build.js, then re-bake (tools/bake/bake.ps1).

    py -3 -I tools/marquee/loreweb_clues.py
"""
import json
import os

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..'))
WEB = os.path.join(ROOT, 'tools', 'marquee', 'loreweb.json')
LORE = os.path.join(ROOT, 'mod', 'src', 'main', 'resources', 'skycraft', 'lore', 'places', 'loreweb.json')
OUT = os.path.join(ROOT, 'mod', 'src', 'main', 'resources', 'skycraft', 'scatter', 'loreweb_clues.json')


def main():
    web = json.load(open(WEB, encoding='utf-8'))
    lore = json.load(open(LORE, encoding='utf-8')).get('places', {})
    places = {}
    for pid in sorted(web['situations']):
        s = web['situations'][pid]
        notes = [n['id'] for n in lore.get(pid, {}).get('notes', [])]
        clues = [c.strip() for c in s.get('clues', []) if c and c.strip()]
        if not clues and not s.get('thread_clue'):
            continue
        places[pid] = {
            'arc': s.get('arc', ''),
            'thread': s.get('thread', ''),
            'clues': clues,
            'thread_clue': (s.get('thread_clue') or '').strip(),
            'note': ('place.%s.web' % pid) if 'web' in notes else '',
            'thread_note': ('place.%s.thread' % pid) if 'thread' in notes else '',
        }
    out = {
        '_doc': 'Generated by tools/marquee/loreweb_clues.py from tools/marquee/loreweb.json. The placeable clues of every '
                'lore-web place: the scene plan (sceneplan bake) sets each one near its place as a LOREWEB_CLUE scene with '
                'a sign carrying the text and, where the place has one, its web/thread note in a barrel.',
        'places': places,
    }
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        json.dump(out, f, ensure_ascii=False, indent=1, sort_keys=False)
        f.write('\n')
    print('wrote %d places, %d clues to %s' % (len(places), sum(len(p['clues']) + (1 if p['thread_clue'] else 0)
                                                           for p in places.values()), os.path.relpath(OUT, ROOT)))


if __name__ == '__main__':
    main()
