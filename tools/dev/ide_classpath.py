"""Regenerate mod/.classpath (+ Java 25 compiler prefs) for the VS Code / Eclipse Java tooling from the REAL Gradle
compile classpath of the NeoForge 26.3 build. Gradle's own `eclipse` task cannot be used: the build keeps its
outputs on E: (skycraftBuildDir) and the Eclipse plugin cannot relativise across drives.

    py -3 tools/dev/ide_classpath.py

Run it after dependency or platform changes; then in VS Code: "Java: Clean Java Language Server Workspace" if the
Problems panel still shows old errors. The files are gitignored (per machine).
"""
import re
import subprocess
import sys
import tempfile
from pathlib import Path
from xml.sax.saxutils import quoteattr

ROOT = Path(__file__).resolve().parents[2]
MOD = ROOT / "mod"
INIT = """
allprojects {
    afterEvaluate { p ->
        p.tasks.register('printIdeClasspath') {
            doLast {
                def out = new File(System.getProperty('ide.cp.out'))
                def files = p.sourceSets.main.compileClasspath.files + p.sourceSets.test.compileClasspath.files
                out.text = files.findAll { it.exists() }.collect { it.absolutePath }.unique().join('\\n')
            }
        }
    }
}
"""


def main():
    with tempfile.TemporaryDirectory() as tmp:
        init, listing = Path(tmp) / "ide_cp.gradle", Path(tmp) / "ide_cp.txt"
        init.write_text(INIT, encoding="utf-8")
        r = subprocess.run([sys.executable, str(ROOT / "tools/dev/build_263.py"), "--offline", "--", "--init-script",
                            str(init), f"-Dide.cp.out={listing}", "printIdeClasspath"], cwd=ROOT)
        if r.returncode or not listing.exists():
            sys.exit("could not read the Gradle classpath (is the build lock free?)")
        libs = [l.strip() for l in listing.read_text(encoding="utf-8").splitlines() if l.strip()]
    lines = ['<?xml version="1.0" encoding="UTF-8"?>',
             '<!-- generated by tools/dev/ide_classpath.py from the real NeoForge 26.3 compile classpath -->',
             '<classpath>']
    for path, output, test in [("src/main/java", "bin/main", False), ("src/main/resources", "bin/main", False),
                               ("src/generated/resources", "bin/main", False), ("src/test/java", "bin/test", True),
                               ("src/test/resources", "bin/test", True)]:
        if (MOD / path).exists():
            attrs = '<attributes><attribute name="test" value="true"/></attributes>' if test else ""
            lines.append(f'\t<classpathentry kind="src" output="{output}" path="{path}">{attrs}</classpathentry>')
    lines.append('\t<classpathentry kind="con" path="org.eclipse.jdt.launching.JRE_CONTAINER/'
                 'org.eclipse.jdt.internal.debug.ui.launcher.StandardVMType/JavaSE-25/"/>')
    lines += [f'\t<classpathentry kind="lib" path={quoteattr(l.replace(chr(92), "/"))}/>' for l in libs]
    lines += ['\t<classpathentry kind="output" path="bin/default"/>', '</classpath>']
    (MOD / ".classpath").write_text("\n".join(lines) + "\n", encoding="utf-8")
    project = MOD / ".project"
    if not project.exists():
        project.write_text('<?xml version="1.0" encoding="UTF-8"?>\n<projectDescription>\n\t<name>' + MOD.name +
                           '</name>\n\t<buildSpec>\n\t\t<buildCommand>\n\t\t\t<name>org.eclipse.jdt.core.javabuilder</name>'
                           '\n\t\t</buildCommand>\n\t</buildSpec>\n\t<natures>\n\t\t<nature>org.eclipse.jdt.core.javanature'
                           '</nature>\n\t</natures>\n</projectDescription>\n', encoding="utf-8")
    prefs = MOD / ".settings/org.eclipse.jdt.core.prefs"
    prefs.parent.mkdir(exist_ok=True)
    s = prefs.read_text(encoding="utf-8") if prefs.exists() else "eclipse.preferences.version=1\n"
    for k in ("org.eclipse.jdt.core.compiler.codegen.targetPlatform", "org.eclipse.jdt.core.compiler.compliance",
              "org.eclipse.jdt.core.compiler.source"):
        s = re.sub(rf"^{re.escape(k)}=.*$", f"{k}=25", s, flags=re.M) if re.search(rf"^{re.escape(k)}=", s, re.M) \
            else s + f"{k}=25\n"
    prefs.write_text(s, encoding="utf-8")
    print(f"mod/.classpath: {len(libs)} libraries (NeoForge 26.3, Java 25)")


if __name__ == "__main__":
    main()
