def load_json(path: str):
    with open(path, encoding="utf-8") as f:
        return json.load(f)


def write_json(path: str, data, indent: int = 2) -> None:
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        json.dump(data, f, indent=indent, ensure_ascii=False)
        f.write("\n")


def generate_dungeon_identities() -> dict[str, int]:
    names = dig.lang_names()
    lore = dig.lore_places()
    used_global: set[str] = set()

    # Seed used_global from existing skyrim/high_rock/hammerfell/cyrodiil identity files for cross-province uniqueness
    for existing_fn in ("skyrim.json", "high_rock.json", "hammerfell.json", "cyrodiil.json"):
        ep = os.path.join(IDENT_DIR, existing_fn)
        if os.path.exists(ep):
            ed = load_json(ep)
            for entry in (ed.get("places") or {}).values():
                if isinstance(entry, dict) and entry.get("boss"):
                    b = entry["boss"]
                    used_global.add(b["name"] if isinstance(b, dict) else str(b))

    target_specs = [
        ("morrowind", "morrowind.json", "morrowind.json"),
        ("black_marsh", "black_marsh.json", "black_marsh.json"),
        ("elsweyr", "elsweyr.json", "elsweyr.json"),
        ("valenwood", "valenwood.json", "valenwood.json"),
        ("summerset", "summerset.json", "summerset.json"),
        ("foreign", "foreign.json", "foreign.json"),
    ]

    counts: dict[str, int] = {}
    for prov_key, pl_file, out_fn in target_specs:
        places_map, skipped = dig.build_province(prov_key, pl_file, names, lore, used=used_global)
        if skipped:
            raise RuntimeError(f"{prov_key}: unexpected skipped dungeons: {skipped}")
        # Ensure every entry has a non-empty bossNote and entrance so F-ORPHAN and lecterns are 100% covered
        for pid, entry in places_map.items():
            if not entry.get("entrance"):
                entry["entrance"] = "orders"
                entry["entranceKind"] = "orders"
            if not entry.get("bossNote"):
                entry["bossNote"] = entry["entrance"] or "orders"
            if not entry.get("why"):
                raise RuntimeError(f"{prov_key}:{pid} missing why citation")
        out_path = os.path.join(IDENT_DIR, out_fn)
        doc = {
            "note": "Generated by tools/content/southern_foreign_encounters_identity.py from the places and the place lore. Do not edit.",
            "places": places_map,
        }
        with open(out_path, "w", encoding="utf-8", newline="\n") as f:
            f.write(dig.dumps(doc))
        counts[prov_key] = len(places_map)
    return counts


def update_scenes() -> int:
    scenes = load_json(SCENES_PATH)
    new_ids = {s["id"] for s in NEW_SCENES}
    kept = [
        s
        for s in scenes
        if s.get("id") not in new_ids
        and not str(s.get("id", "")).startswith(("v8_bm_", "v8_el_", "v8_vw_", "v8_su_", "v8_fl_"))
    ]
    kept.extend(NEW_SCENES)
    write_json(SCENES_PATH, kept, indent=2)
    return len(NEW_SCENES)


