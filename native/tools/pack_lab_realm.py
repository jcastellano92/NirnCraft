#!/usr/bin/env python3
"""Generate the NirnCraft Atlas pack's realm program set (shaders/realm/) from the root programs.

Iris loads a dimension folder's programs instead of the root's (nothing is merged), so the realm folder holds a
copy of every root program stub with `#define NIRNCRAFT_REALM` after the #version line; the shared code under lib/
switches on it (no terrestrial sky, sun, weather or haze; the realm's own sky and authored fog).
dimension.properties maps the realm dimensions to it; unlisted dimensions (the Overworld) use the root programs.

usage: py -3 native/tools/pack_lab_realm.py      (re-run after adding or changing a root program stub)
"""
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[2]
PACK = ROOT / "shaderpack" / "InfiniteATLAS" / "shaders"
REALM = PACK / "realm"
# DimensionMediaPolicy: local media but no terrestrial weather or celestial state (Realm.java: the Deadlands reuse
# the Nether, Sovngarde the End)
DIMENSIONS = ["minecraft:the_nether", "minecraft:the_end", "nirncraft:shivering_isles", "nirncraft:apocrypha",
              "nirncraft:soul_cairn", "nirncraft:coldharbour"]


def main() -> None:
    REALM.mkdir(exist_ok=True)
    for old in REALM.glob("*.?sh"):
        old.unlink()
    count = 0
    for src in sorted(list(PACK.glob("*.vsh")) + list(PACK.glob("*.fsh"))):
        lines = src.read_text(encoding="utf-8").splitlines()
        if not lines or not lines[0].startswith("#version"):
            raise SystemExit(f"{src.name}: first line is not #version")
        out = [lines[0], "#define NIRNCRAFT_REALM  // generated by native/tools/pack_lab_realm.py from ../" + src.name]
        out += lines[1:]
        (REALM / src.name).write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")
        count += 1
    (PACK / "dimension.properties").write_text(
        "# NirnCraft Atlas: realms use shaders/realm/ (generated by native/tools/pack_lab_realm.py); every other\n"
        "# dimension, the Overworld included, uses the root programs\n"
        "dimension.realm = " + " ".join(DIMENSIONS) + "\n", encoding="utf-8", newline="\n")
    print(f"pack_lab_realm: {count} programs -> {REALM.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
