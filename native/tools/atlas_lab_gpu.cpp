// atlas_lab_gpu: atlas_lab's two finalists (adaptive boxes, content-shaped groups; docs/ATLAS-LOD.md) through the
// renderer's own Slang paths ("Slang port"): their GPU layouts (atlas_lod_build.hpp), the kernels of
// shaders/atlas_lod.slang on the CPU backend (Slang -> C++) or on Vulkan (Slang -> SPIR-V), checked against atlas_lab's
// C++ tracers (atlas_lab_scene.hpp: the reference), with timings and memory.
//
//   atlas_lab_gpu blocks=<dir>/blocks.bin volume=<dir>/x.alv [dist=10,50,200,600,1500] [variants=boxes,groups]
//                 [backend=cpu|vulkan] [frames=16] [threads=N] [w=1920 h=1080 reps=3] [quality=1] [out=sheet.png]
//                 [yaw=30 pitch=-12 fov=70 tol=1 fog=0 scale=1 screen=1080 shade=mc grass= foliage= tx= ty= tz=]
//   atlas_lab_gpu synth=<dir>   a small synthetic scene of our own there (blocks.bin, tree.alv, tree.json)
//
// Per distance and representation, the camera and window of true pixels of atlas_lab's table:
//   parity   the kernel's image converged over the frames (the same jitter, seeds and dithering as atlas_lab) against
//            atlas_lab's tracer: iou (soft silhouette), dE / dEmax (CIE76, mean and worst pixel), rgb (largest channel
//            difference, 0..255), diff (share of pixels differing by more than dE 1), steps (the kernel's and the
//            reference's per ray); floor: atlas_lab against itself with other seeds (what the dithering alone moves)
//   quality  (quality=1) iou and dE against ref, atlas_lab's micro-voxel reference (64 samples a pixel)
//   vulkan   (backend=vulkan) the same for the Vulkan image, against the CPU backend's
//   ns/ray   wall time a ray over that window (the object fills it): the CPU backend, atlas_lab, Vulkan (timestamps)
//   timing   one w x h frame through the object (1920 x 1080): the CPU backend (threads), atlas_lab's tracer on the
//            same threads, Vulkan (GPU timestamps, median of 4 x reps frames); ms and rays per second
//   memory   per representation: nodes, bytes a node, the stack a thread; the brick pool they share; what storing
//            every node's face texels would cost instead (faces MB)
// Last stdout line: JSON.
