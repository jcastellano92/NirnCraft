// atlas_lod.slang LodFrame (every member 16 bytes: the same layout in C++, std140 and the generated code)
struct LodFrame {
    float eye[4], fwd[4], right[4], up[4], light0[4], light1[4], sky[4], tint1[4], tint2[4], tint3[4];
    int32_t dims[4], view[4], seq[4];
};
static_assert(sizeof(LodFrame) == 13 * 16, "LodFrame layout");

template <typename T>
struct CpuBuf {
    T* data;
    size_t count;
};
struct U4 {
    uint32_t v[4];
};
struct F4 {
    float v[4];
};
// Must list the globals of atlas_lod.slang in declaration order (a constant buffer is a pointer there).
struct LodGlobals {
    const LodFrame* frame;
    CpuBuf<const U4> nodes;
    CpuBuf<const uint32_t> grid;
    CpuBuf<const U4> bricks;
    CpuBuf<const uint32_t> states;
    CpuBuf<F4> outColor;
    CpuBuf<float> outT;
    CpuBuf<uint32_t> outId;
    CpuBuf<uint32_t> outSteps;
};

// one frame's per-pixel output
struct Pixels {
    std::vector<F4> color;
    std::vector<float> t;
    std::vector<uint32_t> id, steps;
    void resize(size_t n) {
        color.resize(n);
        t.resize(n);
        id.resize(n);
        steps.resize(n);
    }
};

const char* REP_NAME[2] = {"boxes", "groups"};
LodPool pool;
LodTree trees[2];

double msSince(std::chrono::steady_clock::time_point t0) {
    return std::chrono::duration<double, std::milli>(std::chrono::steady_clock::now() - t0).count();
}

template <class F>
void runThreads(int threads, F&& work) {
    std::vector<std::thread> ts;
    for (int t = 0; t < threads; t++) ts.emplace_back(work);
    for (auto& t : ts) t.join();
}

// ---- the CPU backend: the generated kernels, a row of 8 x 8 groups per work item ------------------------------------

void cpuFrame(int rep, const LodFrame& fr, Pixels& out, int threads) {
    uint32_t W = uint32_t(fr.view[0]), H = uint32_t(fr.view[1]);
    size_t n = size_t(W) * H;
    out.resize(n);
    const LodTree& tr = trees[rep];
    LodGlobals g{&fr,
                 {reinterpret_cast<const U4*>(tr.nodes.data()), tr.count()},
                 {pool.grid.data(), pool.grid.size()},
                 {reinterpret_cast<const U4*>(pool.bricks.data()), pool.bricks.size() / 4},
                 {pool.states.data(), pool.states.size()},
                 {out.color.data(), n},
                 {out.t.data(), n},
                 {out.id.data(), n},
                 {out.steps.data(), n}};
    void (*kernel)(void*, void*, void*) = rep == 0 ? boxesMain : groupsMain;
    uint32_t gx = (W + 7) / 8, gy = (H + 7) / 8;
    std::atomic<uint32_t> next{0};
    runThreads(threads, [&] {
        for (uint32_t row; (row = next++) < gy;) {
            LodGroupRange r{{0, row, 0}, {gx, row + 1, 1}};
            kernel(&r, nullptr, &g);
        }
    });
}

// ---- Vulkan: the same kernels as SPIR-V, inputs in device memory, one dispatch a frame ------------------------------

struct VkBuf {
    VkBuffer buf = VK_NULL_HANDLE;
    VkDeviceMemory mem = VK_NULL_HANDLE;
    void* map = nullptr;
    VkDeviceSize size = 0;
};

class Gpu {
public:
    std::string name = "vulkan";

    ~Gpu() {
        if (dev_) {
            vkDeviceWaitIdle(dev_);
            for (VkBuf* b : {&ubo_, &nodes_[0], &nodes_[1], &grid_, &bricks_, &states_, &out_[0], &out_[1], &out_[2], &out_[3], &readback_})
                release(*b);
            if (queries_) vkDestroyQueryPool(dev_, queries_, nullptr);
            if (fence_) vkDestroyFence(dev_, fence_, nullptr);
            if (pool_) vkDestroyCommandPool(dev_, pool_, nullptr);
            if (descPool_) vkDestroyDescriptorPool(dev_, descPool_, nullptr);
            for (int i = 0; i < 2; i++) {
                if (pipe_[i]) vkDestroyPipeline(dev_, pipe_[i], nullptr);
                if (module_[i]) vkDestroyShaderModule(dev_, module_[i], nullptr);
            }
            if (layout_) vkDestroyPipelineLayout(dev_, layout_, nullptr);
            if (setLayout_) vkDestroyDescriptorSetLayout(dev_, setLayout_, nullptr);
            vkDestroyDevice(dev_, nullptr);
        }
        if (inst_) vkDestroyInstance(inst_, nullptr);
    }

    bool init(size_t maxPixels, std::string& err) {
        maxPixels_ = std::max<size_t>(maxPixels, 64);
        if (!vkLoadGlobal(err)) return false;
        VkApplicationInfo app{VK_STRUCTURE_TYPE_APPLICATION_INFO};
        app.pApplicationName = "atlas_lab_gpu";
        app.apiVersion = VK_API_VERSION_1_2;
        VkInstanceCreateInfo ici{VK_STRUCTURE_TYPE_INSTANCE_CREATE_INFO};
        ici.pApplicationInfo = &app;
        if (vkCreateInstance(&ici, nullptr, &inst_) != VK_SUCCESS) return fail(err, "vkCreateInstance failed");
        if (!vkLoadInstance(inst_, err)) return false;
        uint32_t n = 0;
        vkEnumeratePhysicalDevices(inst_, &n, nullptr);
        std::vector<VkPhysicalDevice> devs(n);
        vkEnumeratePhysicalDevices(inst_, &n, devs.data());
        int best = -1, bestScore = -1;
        for (uint32_t i = 0; i < n; i++) {
            VkPhysicalDeviceProperties p;
            vkGetPhysicalDeviceProperties(devs[i], &p);
            int score = p.deviceType == VK_PHYSICAL_DEVICE_TYPE_DISCRETE_GPU ? 3 : p.deviceType == VK_PHYSICAL_DEVICE_TYPE_INTEGRATED_GPU ? 2 : 1;
            if (p.apiVersion >= VK_API_VERSION_1_2 && score > bestScore) best = int(i), bestScore = score;
        }
        if (best < 0) return fail(err, "no Vulkan 1.2 device");
        phys_ = devs[size_t(best)];
        VkPhysicalDeviceProperties p;
        vkGetPhysicalDeviceProperties(phys_, &p);
        name = std::string("vulkan (") + p.deviceName + ")";
        period_ = p.limits.timestampPeriod;
        uint32_t qn = 0;
        vkGetPhysicalDeviceQueueFamilyProperties(phys_, &qn, nullptr);
        std::vector<VkQueueFamilyProperties> qf(qn);
        vkGetPhysicalDeviceQueueFamilyProperties(phys_, &qn, qf.data());
        family_ = UINT32_MAX;
        for (uint32_t i = 0; i < qn && family_ == UINT32_MAX; i++)
            if ((qf[i].queueFlags & VK_QUEUE_COMPUTE_BIT) && qf[i].timestampValidBits > 0) family_ = i;
        if (family_ == UINT32_MAX) return fail(err, "no compute queue with timestamps");
        float prio = 1.0f;
        VkDeviceQueueCreateInfo qci{VK_STRUCTURE_TYPE_DEVICE_QUEUE_CREATE_INFO};
        qci.queueFamilyIndex = family_;
        qci.queueCount = 1;
        qci.pQueuePriorities = &prio;
        VkDeviceCreateInfo dci{VK_STRUCTURE_TYPE_DEVICE_CREATE_INFO};
        dci.queueCreateInfoCount = 1;
        dci.pQueueCreateInfos = &qci;
        if (vkCreateDevice(phys_, &dci, nullptr, &dev_) != VK_SUCCESS) return fail(err, "vkCreateDevice failed");
        vkGetDeviceQueue(dev_, family_, 0, &queue_);

        VkDescriptorSetLayoutBinding b[9];
        for (uint32_t i = 0; i < 9; i++)
            b[i] = {i, i == 0 ? VK_DESCRIPTOR_TYPE_UNIFORM_BUFFER : VK_DESCRIPTOR_TYPE_STORAGE_BUFFER, 1, VK_SHADER_STAGE_COMPUTE_BIT, nullptr};
        VkDescriptorSetLayoutCreateInfo dl{VK_STRUCTURE_TYPE_DESCRIPTOR_SET_LAYOUT_CREATE_INFO};
        dl.bindingCount = 9;
        dl.pBindings = b;
        if (vkCreateDescriptorSetLayout(dev_, &dl, nullptr, &setLayout_) != VK_SUCCESS) return fail(err, "set layout");
        VkPipelineLayoutCreateInfo pl{VK_STRUCTURE_TYPE_PIPELINE_LAYOUT_CREATE_INFO};
        pl.setLayoutCount = 1;
        pl.pSetLayouts = &setLayout_;
        if (vkCreatePipelineLayout(dev_, &pl, nullptr, &layout_) != VK_SUCCESS) return fail(err, "pipeline layout");
        const uint32_t* code[2] = {atlas_lod_boxes_spv, atlas_lod_groups_spv};
        size_t size[2] = {atlas_lod_boxes_spv_size, atlas_lod_groups_spv_size};
        for (int i = 0; i < 2; i++) {
            VkShaderModuleCreateInfo smci{VK_STRUCTURE_TYPE_SHADER_MODULE_CREATE_INFO};
            smci.codeSize = size[i];
            smci.pCode = code[i];
            if (vkCreateShaderModule(dev_, &smci, nullptr, &module_[i]) != VK_SUCCESS) return fail(err, "shader module");
            VkComputePipelineCreateInfo cp{VK_STRUCTURE_TYPE_COMPUTE_PIPELINE_CREATE_INFO};
            cp.stage = {VK_STRUCTURE_TYPE_PIPELINE_SHADER_STAGE_CREATE_INFO};
            cp.stage.stage = VK_SHADER_STAGE_COMPUTE_BIT;
            cp.stage.module = module_[i];
            cp.stage.pName = "main";
            cp.layout = layout_;
            if (vkCreateComputePipelines(dev_, VK_NULL_HANDLE, 1, &cp, nullptr, &pipe_[i]) != VK_SUCCESS) return fail(err, "pipeline");
        }
        VkDescriptorPoolSize ps[2] = {{VK_DESCRIPTOR_TYPE_UNIFORM_BUFFER, 2}, {VK_DESCRIPTOR_TYPE_STORAGE_BUFFER, 16}};
        VkDescriptorPoolCreateInfo dp{VK_STRUCTURE_TYPE_DESCRIPTOR_POOL_CREATE_INFO};
        dp.maxSets = 2;
        dp.poolSizeCount = 2;
        dp.pPoolSizes = ps;
        if (vkCreateDescriptorPool(dev_, &dp, nullptr, &descPool_) != VK_SUCCESS) return fail(err, "descriptor pool");
        VkDescriptorSetLayout two[2] = {setLayout_, setLayout_};
        VkDescriptorSetAllocateInfo da{VK_STRUCTURE_TYPE_DESCRIPTOR_SET_ALLOCATE_INFO};
        da.descriptorPool = descPool_;
        da.descriptorSetCount = 2;
        da.pSetLayouts = two;
        if (vkAllocateDescriptorSets(dev_, &da, set_) != VK_SUCCESS) return fail(err, "descriptor sets");
        VkCommandPoolCreateInfo cpi{VK_STRUCTURE_TYPE_COMMAND_POOL_CREATE_INFO};
        cpi.flags = VK_COMMAND_POOL_CREATE_RESET_COMMAND_BUFFER_BIT;
        cpi.queueFamilyIndex = family_;
        if (vkCreateCommandPool(dev_, &cpi, nullptr, &pool_) != VK_SUCCESS) return fail(err, "command pool");
        VkCommandBufferAllocateInfo ca{VK_STRUCTURE_TYPE_COMMAND_BUFFER_ALLOCATE_INFO};
        ca.commandPool = pool_;
        ca.level = VK_COMMAND_BUFFER_LEVEL_PRIMARY;
        ca.commandBufferCount = 1;
        if (vkAllocateCommandBuffers(dev_, &ca, &cmd_) != VK_SUCCESS) return fail(err, "command buffer");
        VkFenceCreateInfo fci{VK_STRUCTURE_TYPE_FENCE_CREATE_INFO};
        if (vkCreateFence(dev_, &fci, nullptr, &fence_) != VK_SUCCESS) return fail(err, "fence");
        VkQueryPoolCreateInfo qp{VK_STRUCTURE_TYPE_QUERY_POOL_CREATE_INFO};
        qp.queryType = VK_QUERY_TYPE_TIMESTAMP;
        qp.queryCount = 2;
        if (vkCreateQueryPool(dev_, &qp, nullptr, &queries_) != VK_SUCCESS) return fail(err, "query pool");
        size_t px = maxPixels_;
        return ensure(ubo_, sizeof(LodFrame), true, err) && ensure(out_[0], px * 16, false, err) && ensure(out_[1], px * 4, false, err) &&
               ensure(out_[2], px * 4, false, err) && ensure(out_[3], px * 4, false, err) && ensure(readback_, px * 28, true, err, true);
    }

    // the inputs once, into device-local memory
    bool upload(std::string& err) {
        const std::vector<uint32_t>* src[5] = {&trees[0].nodes, &trees[1].nodes, &pool.grid, &pool.bricks, &pool.states};
        VkBuf* dst[5] = {&nodes_[0], &nodes_[1], &grid_, &bricks_, &states_};
        size_t most = 64;
        for (auto* s : src) most = std::max(most, s->size() * 4);
        VkBuf staging;
        if (!ensure(staging, most, true, err)) return false;
        for (int i = 0; i < 5; i++) {
            size_t bytes = std::max<size_t>(src[i]->size() * 4, 16);
            if (!ensure(*dst[i], bytes, false, err)) return release(staging), false;
            if (src[i]->empty()) continue;
            std::memcpy(staging.map, src[i]->data(), src[i]->size() * 4);
            begin();
            VkBufferCopy c{0, 0, src[i]->size() * 4};
            vkCmdCopyBuffer(cmd_, staging.buf, dst[i]->buf, 1, &c);
            barrier(VK_ACCESS_TRANSFER_WRITE_BIT, VK_ACCESS_SHADER_READ_BIT, VK_PIPELINE_STAGE_TRANSFER_BIT, VK_PIPELINE_STAGE_COMPUTE_SHADER_BIT);
            if (!submitWait(err)) return release(staging), false;
        }
        release(staging);
        for (int r = 0; r < 2; r++) {
            VkDescriptorBufferInfo bi[9] = {{ubo_.buf, 0, sizeof(LodFrame)},      {nodes_[r].buf, 0, VK_WHOLE_SIZE},
                                            {grid_.buf, 0, VK_WHOLE_SIZE},          {bricks_.buf, 0, VK_WHOLE_SIZE},
                                            {states_.buf, 0, VK_WHOLE_SIZE},        {out_[0].buf, 0, VK_WHOLE_SIZE},
                                            {out_[1].buf, 0, VK_WHOLE_SIZE},        {out_[2].buf, 0, VK_WHOLE_SIZE},
                                            {out_[3].buf, 0, VK_WHOLE_SIZE}};
            VkWriteDescriptorSet w[9];
            for (uint32_t i = 0; i < 9; i++) {
                w[i] = {VK_STRUCTURE_TYPE_WRITE_DESCRIPTOR_SET};
                w[i].dstSet = set_[r];
                w[i].dstBinding = i;
                w[i].descriptorCount = 1;
                w[i].descriptorType = i == 0 ? VK_DESCRIPTOR_TYPE_UNIFORM_BUFFER : VK_DESCRIPTOR_TYPE_STORAGE_BUFFER;
                w[i].pBufferInfo = &bi[i];
            }
            vkUpdateDescriptorSets(dev_, 9, w, 0, nullptr);
        }
        return true;
    }

    // one frame of representation rep; out (when given) read back; ms: the dispatch alone (GPU timestamps)
    bool frame(int rep, const LodFrame& fr, Pixels* out, double& ms, std::string& err) {
        size_t n = size_t(fr.view[0]) * size_t(fr.view[1]);
        if (n > maxPixels_) return fail(err, "frame larger than the output buffers");
        std::memcpy(ubo_.map, &fr, sizeof fr);
        begin();
        vkCmdResetQueryPool(cmd_, queries_, 0, 2);
        vkCmdWriteTimestamp(cmd_, VK_PIPELINE_STAGE_TOP_OF_PIPE_BIT, queries_, 0);
        vkCmdBindPipeline(cmd_, VK_PIPELINE_BIND_POINT_COMPUTE, pipe_[rep]);
        vkCmdBindDescriptorSets(cmd_, VK_PIPELINE_BIND_POINT_COMPUTE, layout_, 0, 1, &set_[rep], 0, nullptr);
        vkCmdDispatch(cmd_, uint32_t(fr.view[0] + 7) / 8, uint32_t(fr.view[1] + 7) / 8, 1);
        vkCmdWriteTimestamp(cmd_, VK_PIPELINE_STAGE_BOTTOM_OF_PIPE_BIT, queries_, 1);
        if (out) {
            barrier(VK_ACCESS_SHADER_WRITE_BIT, VK_ACCESS_TRANSFER_READ_BIT, VK_PIPELINE_STAGE_COMPUTE_SHADER_BIT, VK_PIPELINE_STAGE_TRANSFER_BIT);
            VkDeviceSize at[4] = {0, n * 16, n * 20, n * 24}, sz[4] = {n * 16, n * 4, n * 4, n * 4};
            for (int i = 0; i < 4; i++) {
                VkBufferCopy c{0, at[i], sz[i]};
                vkCmdCopyBuffer(cmd_, out_[i].buf, readback_.buf, 1, &c);
            }
            barrier(VK_ACCESS_TRANSFER_WRITE_BIT, VK_ACCESS_HOST_READ_BIT, VK_PIPELINE_STAGE_TRANSFER_BIT, VK_PIPELINE_STAGE_HOST_BIT);
        }
        if (!submitWait(err)) return false;
        uint64_t ts[2] = {};
        if (vkGetQueryPoolResults(dev_, queries_, 0, 2, sizeof ts, ts, 8, VK_QUERY_RESULT_64_BIT | VK_QUERY_RESULT_WAIT_BIT) != VK_SUCCESS)
            return fail(err, "timestamps");
        ms = double(ts[1] - ts[0]) * period_ * 1e-6;
        if (out) {
            out->resize(n);
            const uint8_t* m = static_cast<const uint8_t*>(readback_.map);
            std::memcpy(out->color.data(), m, n * 16);
            std::memcpy(out->t.data(), m + n * 16, n * 4);
            std::memcpy(out->id.data(), m + n * 20, n * 4);
            std::memcpy(out->steps.data(), m + n * 24, n * 4);
        }
        return true;
    }

private:
    static bool fail(std::string& err, std::string m) {
        err = std::move(m);
        return false;
    }

    uint32_t memoryType(uint32_t bits, VkMemoryPropertyFlags want) {
        VkPhysicalDeviceMemoryProperties mp;
        vkGetPhysicalDeviceMemoryProperties(phys_, &mp);
        for (uint32_t t = 0; t < mp.memoryTypeCount; t++)
            if ((bits & (1u << t)) && (mp.memoryTypes[t].propertyFlags & want) == want) return t;
        return UINT32_MAX;
    }

    void release(VkBuf& b) {
        if (b.map) vkUnmapMemory(dev_, b.mem);
        if (b.buf) vkDestroyBuffer(dev_, b.buf, nullptr);
        if (b.mem) vkFreeMemory(dev_, b.mem, nullptr);
        b = {};
    }

    // host: host-visible (cached when asked: readback); else device-local
    bool ensure(VkBuf& b, size_t size, bool host, std::string& err, bool cached = false) {
        size = std::max<size_t>(size, 64);
        if (b.buf && b.size >= size) return true;
        release(b);
        VkBufferCreateInfo bc{VK_STRUCTURE_TYPE_BUFFER_CREATE_INFO};
        bc.size = size;
        bc.usage = VK_BUFFER_USAGE_STORAGE_BUFFER_BIT | VK_BUFFER_USAGE_UNIFORM_BUFFER_BIT | VK_BUFFER_USAGE_TRANSFER_SRC_BIT |
                   VK_BUFFER_USAGE_TRANSFER_DST_BIT;
        if (vkCreateBuffer(dev_, &bc, nullptr, &b.buf) != VK_SUCCESS) return fail(err, "vkCreateBuffer");
        VkMemoryRequirements req;
        vkGetBufferMemoryRequirements(dev_, b.buf, &req);
        VkMemoryPropertyFlags hv = VK_MEMORY_PROPERTY_HOST_VISIBLE_BIT | VK_MEMORY_PROPERTY_HOST_COHERENT_BIT;
        uint32_t type = host ? memoryType(req.memoryTypeBits, hv | (cached ? VK_MEMORY_PROPERTY_HOST_CACHED_BIT : 0u))
                             : memoryType(req.memoryTypeBits, VK_MEMORY_PROPERTY_DEVICE_LOCAL_BIT);
        if (type == UINT32_MAX && host) type = memoryType(req.memoryTypeBits, hv);
        if (type == UINT32_MAX) return fail(err, "no suitable memory type");
        VkMemoryAllocateInfo ma{VK_STRUCTURE_TYPE_MEMORY_ALLOCATE_INFO};
        ma.allocationSize = req.size;
        ma.memoryTypeIndex = type;
        if (vkAllocateMemory(dev_, &ma, nullptr, &b.mem) != VK_SUCCESS) return fail(err, "vkAllocateMemory");
        vkBindBufferMemory(dev_, b.buf, b.mem, 0);
        if (host && vkMapMemory(dev_, b.mem, 0, VK_WHOLE_SIZE, 0, &b.map) != VK_SUCCESS) return fail(err, "vkMapMemory");
        b.size = size;
        return true;
    }

    void begin() {
        vkResetCommandBuffer(cmd_, 0);
        VkCommandBufferBeginInfo bi{VK_STRUCTURE_TYPE_COMMAND_BUFFER_BEGIN_INFO};
        bi.flags = VK_COMMAND_BUFFER_USAGE_ONE_TIME_SUBMIT_BIT;
        vkBeginCommandBuffer(cmd_, &bi);
    }

    bool submitWait(std::string& err) {
        vkEndCommandBuffer(cmd_);
        VkSubmitInfo si{VK_STRUCTURE_TYPE_SUBMIT_INFO};
        si.commandBufferCount = 1;
        si.pCommandBuffers = &cmd_;
        vkResetFences(dev_, 1, &fence_);
        if (vkQueueSubmit(queue_, 1, &si, fence_) != VK_SUCCESS) return fail(err, "vkQueueSubmit failed");
        if (vkWaitForFences(dev_, 1, &fence_, VK_TRUE, 10'000'000'000ull) != VK_SUCCESS) return fail(err, "the GPU did not finish (10 s)");
        return true;
    }

    void barrier(VkAccessFlags src, VkAccessFlags dst, VkPipelineStageFlags from, VkPipelineStageFlags to) {
        VkMemoryBarrier mb{VK_STRUCTURE_TYPE_MEMORY_BARRIER};
        mb.srcAccessMask = src;
        mb.dstAccessMask = dst;
        vkCmdPipelineBarrier(cmd_, from, to, 0, 1, &mb, 0, nullptr, 0, nullptr);
    }

    VkInstance inst_ = VK_NULL_HANDLE;
    VkPhysicalDevice phys_ = VK_NULL_HANDLE;
    VkDevice dev_ = VK_NULL_HANDLE;
    VkQueue queue_ = VK_NULL_HANDLE;
    uint32_t family_ = 0;
    float period_ = 1.0f;
    size_t maxPixels_ = 0;
    VkShaderModule module_[2] = {};
    VkPipeline pipe_[2] = {};
    VkDescriptorSetLayout setLayout_ = VK_NULL_HANDLE;
    VkPipelineLayout layout_ = VK_NULL_HANDLE;
    VkDescriptorPool descPool_ = VK_NULL_HANDLE;
    VkDescriptorSet set_[2] = {};
    VkCommandPool pool_ = VK_NULL_HANDLE;
    VkCommandBuffer cmd_ = VK_NULL_HANDLE;
    VkFence fence_ = VK_NULL_HANDLE;
    VkQueryPool queries_ = VK_NULL_HANDLE;
    VkBuf ubo_, nodes_[2], grid_, bricks_, states_, out_[4], readback_;
};

// ---- the camera and atlas_lab's own render loop ---------------------------------------------------------------------

struct Cam {
    V3 fwd, right, up;
    float pa = 0, tolPix = 1, fog = 0;
};

// a w x h window whose view axis goes through pixel (cx, cy), from eye; atlas_lab's table uses w = h = 2 * half,
// cx = cy = half
struct View {
    int w = 0, h = 0, cx = 0, cy = 0;
    V3 eye;
    float trans = 1;  // the fog's transmittance at the object
};

LodFrame lodFrame(const View& v, const Cam& c, int rep, int seq) {
    LodFrame f{};
    auto set3 = [](float* d, V3 s, float w) { d[0] = s.x, d[1] = s.y, d[2] = s.z, d[3] = w; };
    set3(f.eye, v.eye, c.pa);
    set3(f.fwd, c.fwd, c.tolPix);
    set3(f.right, c.right, v.trans);
    set3(f.up, c.up, c.fog > 0 ? 1.f : 0.f);
    float l[6];
    for (int k = 0; k < 6; k++) l[k] = lit({1, 1, 1}, k).r;  // atlas_lab's face light, exactly
    for (int k = 0; k < 4; k++) f.light0[k] = l[k];
    f.light1[0] = l[4], f.light1[1] = l[5];
    set3(f.sky, {SKY.r, SKY.g, SKY.b}, 0);
    set3(f.tint1, {tintGrass.r, tintGrass.g, tintGrass.b}, 0);
    set3(f.tint2, {tintFoliage.r, tintFoliage.g, tintFoliage.b}, 0);
    set3(f.tint3, {0x3F, 0x76, 0xE4}, 0);
    f.dims[0] = vol.sx, f.dims[1] = vol.sy, f.dims[2] = vol.sz, f.dims[3] = trees[rep].root;
    f.view[0] = v.w, f.view[1] = v.h, f.view[2] = v.cx, f.view[3] = v.cy;
    f.seq[0] = seq;
    return f;
}

// atlas_lab's render() for ref, boxes and groups, line for line (one sample a frame, ref 4), over any window
Image labRender(const std::string& v, const View& vw, const Cam& c, int nf, int offset, int threads, double* stepsOut) {
    bool isRef = v == "ref", boxed = v == "boxes";
    int spp = isRef ? 4 : 1, W = vw.w, H = vw.h;
    Image img{W, H, std::vector<RGB>(size_t(W) * H), std::vector<float>(size_t(W) * H, 0)};
    std::atomic<long long> steps{0}, rays{0};
    for (int f = 0; f < nf; f++) {
        std::atomic<int> next{0};
        runThreads(threads, [&] {
            long long st = 0, n = 0;
            for (int py; (py = next++) < H;)
                for (int px = 0; px < W; px++) {
                    RGB acc{};
                    float hit = 0;
                    for (int s = 0; s < spp; s++) {
                        int k = (f + offset) * spp + s + 1;
                        float jx = 0, jy = 0, fr = 0.5f;
                        for (int i = k; i; i /= 2, fr *= 0.5f) jx += fr * (i % 2);
                        fr = 1.f / 3;
                        for (int i = k; i; i /= 3, fr /= 3) jy += fr * (i % 3);
                        float ox = (px - vw.cx + jx) * c.pa, oy = (py - vw.cy + jy) * c.pa;
                        V3 dir = norm(c.fwd + c.right * ox - c.up * oy);
                        uint32_t seed = hash(uint32_t(px + 4096 * py) ^ hash(uint32_t((f + offset) * 977 + s)));
                        Sample sm;
                        if (isRef) {
                            sm = traceMicro(vw.eye, dir);
                        } else {
                            float dither = 0.7f + 0.6f * hashf(px, py, f + offset, 0xB0C5u);
                            float tol = c.tolPix * dither / std::max(vw.trans, 0.02f);
                            sm = boxed ? traceBoxes(vw.eye, dir, c.pa, tol, false, seed) : traceGroups(vw.eye, dir, c.pa, tol, false, seed);
                        }
                        st += sm.steps;
                        n++;
                        RGB col = sm.hit ? sm.c : SKY;
                        if (c.fog > 0 && sm.hit) {
                            float trans = vw.trans;
                            col.r = col.r * trans + SKY.r * (1 - trans), col.g = col.g * trans + SKY.g * (1 - trans), col.b = col.b * trans + SKY.b * (1 - trans);
                        }
                        acc.r += col.r, acc.g += col.g, acc.b += col.b;
                        hit += sm.hit ? 1.f : 0.f;
                    }
                    size_t i = size_t(px + W * py);
                    RGB col{acc.r / spp, acc.g / spp, acc.b / spp};
                    img.c[i].r += col.r / nf, img.c[i].g += col.g / nf, img.c[i].b += col.b / nf;
                    img.a[i] += hit / spp / nf;
                }
            steps += st;
            rays += n;
        });
    }
    if (stepsOut) *stepsOut = rays ? double(steps) / double(rays) : 0;
    return img;
}

// the kernel's frames converged as atlas_lab converges its own (img += colour / frames)
template <class FrameFn>
Image kernelRender(const View& vw, int nf, int offset, double* stepsOut, FrameFn&& oneFrame) {
    int W = vw.w, H = vw.h;
    Image img{W, H, std::vector<RGB>(size_t(W) * H), std::vector<float>(size_t(W) * H, 0)};
    Pixels px;
    double steps = 0;
    for (int f = 0; f < nf; f++) {
        if (!oneFrame(f + offset, px)) return {};
        for (size_t i = 0; i < img.c.size(); i++) {
            const F4& c = px.color[i];
            img.c[i].r += c.v[0] / nf, img.c[i].g += c.v[1] / nf, img.c[i].b += c.v[2] / nf;
            img.a[i] += c.v[3] / 1 / nf;
            steps += px.steps[i];
        }
    }
    if (stepsOut) *stepsOut = steps / (double(img.c.size()) * nf);
    return img;
}

// ---- metrics --------------------------------------------------------------------------------------------------------

struct Cmp {
    double iou = 1, de = 0, deMax = 0, rgb = 0, diff = 0;
};
Cmp compare(const Image& x, const Image& y) {
    Cmp m;
    double inter = 0, uni = 0, de = 0;
    int n = 0, over = 0;
    for (size_t i = 0; i < x.a.size(); i++) {
        inter += std::min(x.a[i], y.a[i]);
        uni += std::max(x.a[i], y.a[i]);
        m.rgb = std::max({m.rgb, double(std::fabs(x.c[i].r - y.c[i].r)), double(std::fabs(x.c[i].g - y.c[i].g)), double(std::fabs(x.c[i].b - y.c[i].b))});
        if (std::max(x.a[i], y.a[i]) <= 0.01f) continue;
        double d = deltaE(x.c[i], y.c[i]);
        de += d;
        m.deMax = std::max(m.deMax, d);
        over += d > 1.0;
        n++;
    }
    m.iou = uni > 0 ? inter / uni : 1;
    m.de = n ? de / n : 0;
    m.diff = n ? double(over) / n : 0;
    return m;
}

void blit(std::vector<uint32_t>& sheet, int sheetW, const Image& img, int ox, int oy, int size) {
    if (img.w <= 0) return;
    int W = img.w;
    for (int y = 0; y < size; y++)
        for (int x = 0; x < size; x++) {
            int sx0 = x * W / size, sx1 = std::max(sx0 + 1, (x + 1) * W / size);
            int sy0 = y * W / size, sy1 = std::max(sy0 + 1, (y + 1) * W / size);
            RGB c{};
            int k = 0;
            for (int yy = sy0; yy < sy1; yy++)
                for (int xx = sx0; xx < sx1; xx++, k++) {
                    const RGB& p = img.c[size_t(xx + W * yy)];
                    c.r += p.r, c.g += p.g, c.b += p.b;
                }
            auto ch = [&](float v2) { return uint32_t(std::clamp(v2 / k, 0.f, 255.f)); };
            sheet[size_t(ox + x) + size_t(sheetW) * size_t(oy + y)] = 0xFF000000u | ch(c.b) << 16 | ch(c.g) << 8 | ch(c.r);
        }
    for (int x = 0; x < size; x++) sheet[size_t(ox + x) + size_t(sheetW) * size_t(oy)] = 0xFF000000u;
    for (int y = 0; y < size; y++) sheet[size_t(ox) + size_t(sheetW) * size_t(oy + y)] = 0xFF000000u;
}

// ---- synth=<dir>: a small scene of our own (no game assets), as AtlasLabExport writes one ---------------------------
// grass and dirt ground with a pond, two trees (log trunks, cutout leaf crowns), a stone hut with a door, a window
// and a slab roof, a fence with a lantern, tufts of grass

struct SynthState {
    const char* name;
    uint8_t cls, emit, flags, tint;
    uint64_t mask;
    uint32_t base;  // RGB
    float holes;    // the share of texels a cutout leaves empty
};

bool writeSynth(const std::string& dir) {
    auto column = [](int x0, int x1, int z0, int z1, int y0, int y1) {
        uint64_t m = 0;
        for (int y = y0; y <= y1; y++)
            for (int z = z0; z <= z1; z++)
                for (int x = x0; x <= x1; x++) m |= 1ull << (x + 4 * (z + 4 * y));
        return m;
    };
    const uint64_t FULL = ~0ull;
    const SynthState st[] = {
        {"Block{minecraft:air}", 5, 0, 0, 0, 0, 0, 0},
        {"Block{minecraft:grass_block}[snowy=false]", 0, 0, 1 | 4 | 8, 1, FULL, 0x9A9A9A, 0},
        {"Block{minecraft:dirt}", 0, 0, 4 | 8, 0, FULL, 0x866043, 0},
        {"Block{minecraft:oak_log}[axis=y]", 0, 0, 4 | 8, 0, FULL, 0x6B5130, 0},
        {"Block{minecraft:oak_leaves}[distance=1,persistent=false,waterlogged=false]", 1, 0, 1 | 4 | 8, 2, FULL, 0x8C8C8C, 0.35f},
        {"Block{minecraft:stone_bricks}", 0, 0, 4 | 8, 0, FULL, 0x7A7A7A, 0},
        {"Block{minecraft:oak_slab}[type=bottom,waterlogged=false]", 5, 0, 4, 0, column(0, 3, 0, 3, 0, 1), 0xA2834F, 0},
        {"Block{minecraft:oak_fence}[east=false,north=false,south=false,waterlogged=false,west=false]", 5, 0, 4, 0, column(1, 2, 1, 2, 0, 3), 0x9C7F4E, 0},
        {"Block{minecraft:water}[level=0]", 2, 0, 1, 3, 0, 0xFFFFFF, 0},
        {"Block{minecraft:short_grass}", 4, 0, 1 | 4, 1, column(0, 3, 0, 3, 0, 2), 0x949494, 0.55f},
        {"Block{minecraft:lantern}[hanging=false,waterlogged=false]", 3, 15, 4, 0, column(1, 2, 1, 2, 0, 1), 0xE8B04A, 0},
    };
    const int N = int(sizeof st / sizeof st[0]);
    std::vector<uint8_t> out = {'A', 'L', 'B', '1'};
    auto put = [&](uint64_t v, int bytes) {
        for (int i = 0; i < bytes; i++) out.push_back(uint8_t(v >> (8 * i)));
    };
    put(uint32_t(N), 4);
    for (int id = 0; id < N; id++) {
        const SynthState& s = st[id];
        std::string name = s.name;
        put(uint32_t(id), 4);
        put(name.size(), 2);
        out.insert(out.end(), name.begin(), name.end());
        put(s.cls, 1), put(s.emit, 1), put(s.flags, 1), put(s.tint, 1);
        put(s.mask, 8);
        uint32_t faces[6][16] = {};
        double sum[3] = {0, 0, 0}, wsum = 0;
        if (s.flags & 4)
            for (int f = 0; f < 6; f++)
                for (int t = 0; t < 16; t++) {
                    float h = hashf(id, f, t, 0x51D7u), shade = 0.82f + 0.36f * hashf(t, id, f, 0x7E47u);
                    if (s.holes > 0 && h < s.holes) continue;  // a hole in the cutout
                    uint32_t c = s.base;
                    if (id == 1 && f != 1) c = 0x866043;       // grass: dirt sides and bottom (tinted all over, as the lab does)
                    if (id == 3 && f <= 1) c = 0xB8945F;       // log: its rings
                    uint32_t ch[3] = {(c >> 16) & 255, (c >> 8) & 255, c & 255};
                    uint32_t px = 0xFF000000u;
                    for (int k = 0; k < 3; k++) {
                        uint32_t v = uint32_t(std::clamp(ch[k] * shade, 0.f, 255.f));
                        px |= v << (16 - 8 * k);
                        sum[k] += v;
                    }
                    wsum += 1;
                    faces[f][t] = px;
                }
        uint32_t mean = wsum > 0 ? 0xFF000000u | uint32_t(sum[0] / wsum) << 16 | uint32_t(sum[1] / wsum) << 8 | uint32_t(sum[2] / wsum) : 0;
        put(mean, 4);
        for (int f = 0; f < 6; f++)
            for (int t = 0; t < 16; t++) put(faces[f][t], 4);
    }
    std::ofstream fb(dir + "/blocks.bin", std::ios::binary);
    fb.write(reinterpret_cast<const char*>(out.data()), std::streamsize(out.size()));
    if (!fb) return false;

    const int sx = 40, sy = 20, sz = 40;
    std::vector<uint32_t> ids(size_t(sx) * sy * sz, 0);
    auto set = [&](int x, int y, int z, uint32_t id) {
        if (x >= 0 && y >= 0 && z >= 0 && x < sx && y < sy && z < sz) ids[size_t(x + sx * (z + sz * y))] = id;
    };
    auto get = [&](int x, int y, int z) { return ids[size_t(x + sx * (z + sz * y))]; };
    for (int z = 0; z < sz; z++)
        for (int x = 0; x < sx; x++) {
            set(x, 0, z, 2);
            bool pond = x >= 27 && x <= 34 && z >= 4 && z <= 10;
            set(x, 1, z, pond ? 8 : 1);
        }
    auto tree = [&](int tx, int tz, int top, float r, int cy) {
        for (int y = 2; y <= top; y++) set(tx, y, tz, 3);
        int R = int(std::ceil(r));
        for (int y = cy - R; y <= cy + R; y++)
            for (int z = tz - R; z <= tz + R; z++)
                for (int x = tx - R; x <= tx + R; x++) {
                    float dx = float(x - tx), dy = (y - cy) * 1.2f, dz = float(z - tz);
                    if (dx * dx + dy * dy + dz * dz <= r * r && y >= 3 && get(x, y, z) == 0) set(x, y, z, 4);
                }
    };
    tree(15, 22, 8, 3.6f, 9);
    tree(31, 30, 6, 2.6f, 7);
    for (int y = 2; y <= 5; y++)  // the hut: hollow stone walls, a door and a window
        for (int z = 4; z <= 10; z++)
            for (int x = 4; x <= 10; x++)
                if (x == 4 || x == 10 || z == 4 || z == 10) set(x, y, z, 5);
    set(7, 2, 4, 0), set(7, 3, 4, 0), set(4, 4, 7, 0);
    for (int z = 3; z <= 11; z++)
        for (int x = 3; x <= 11; x++) set(x, 6, z, 6);
    for (int x = 4; x <= 12; x++) set(x, 2, 16, 7);
    set(12, 3, 16, 10);
    for (int z = 0; z < sz; z++)
        for (int x = 0; x < sx; x++)
            if (get(x, 1, z) == 1 && get(x, 2, z) == 0 && hashf(x, 0, z, 0x6A55u) < 0.07f) set(x, 2, z, 9);
    std::vector<uint8_t> v = {'A', 'L', 'V', '1'};
    auto put32 = [&](uint32_t x) {
        for (int i = 0; i < 4; i++) v.push_back(uint8_t(x >> (8 * i)));
    };
    for (int x : {0, 60, 0, sx, sy, sz}) put32(uint32_t(x));
    for (uint32_t id : ids) put32(id);
    std::ofstream fv(dir + "/tree.alv", std::ios::binary);
    fv.write(reinterpret_cast<const char*>(v.data()), std::streamsize(v.size()));
    std::ofstream fj(dir + "/tree.json");
    fj << "{\"grass\": \"79C05A\", \"foliage\": \"59AE30\", \"water\": \"3F76E4\"}\n";
    if (!fv || !fj) return false;
    std::fprintf(stderr, "atlas_lab_gpu: synthetic scene (%d states, %d x %d x %d blocks) in %s\n", N, sx, sy, sz, dir.c_str());
    return true;
}

