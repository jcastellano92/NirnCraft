"""Far colours of blocks, as the near field shows them: the mean of each block's top texture (through its blockstate
and model JSON), from the game's client jar and the mod's own assets. Writes AetherBlockColors.java (the mod's aether
package): a sorted table of "namespace:block" -> sRGB, read by AetherMaterials. Tinted textures (grass tops, leaves,
vines) stay grey: the far field tints them with the biome's colour itself.

    py -3 -I native/tools/export_block_colors.py <client.jar> <mod resources dir> <out .java>
"""
import io
import json
import sys
import zipfile

from PIL import Image


class Assets:
    def __init__(self, jar, res):
        self.z = zipfile.ZipFile(jar)
        self.res = res
        self.names = set(self.z.namelist())

    def read(self, ns, path):
        p = f'assets/{ns}/{path}'
        if ns != 'minecraft':
            try:
                with open(f'{self.res}/{p}', 'rb') as f:
                    return f.read()
            except OSError:
                return None
        return self.z.read(p) if p in self.names else None

    def json(self, ns, path):
        b = self.read(ns, path)
        return json.loads(b) if b else None


def split(ident, default='minecraft'):
    ident = ident.replace('block/', '', 1) if ident.startswith('block/') else ident
    if ':' in ident:
        ns, p = ident.split(':', 1)
    else:
        ns, p = default, ident
    return ns, p


def model_textures(a, ns, model, depth=0):
    """Texture variables of a block model, following parents."""
    if depth > 8:
        return {}
    mns, mp = split(model, ns)
    if not mp.startswith('block/') and '/' not in mp:
        mp = 'block/' + mp
    j = a.json(mns, f'models/{mp}.json')
    if not j:
        return {}
    tex = {}
    if 'parent' in j:
        tex.update(model_textures(a, mns, j['parent'], depth + 1))
    tex.update(j.get('textures', {}))
    return tex


def resolve(tex, key, depth=0):
    v = tex.get(key)
    while isinstance(v, str) and v.startswith('#') and depth < 8:
        v = tex.get(v[1:])
        depth += 1
    return v


def first_model(bs):
    if not bs:
        return None
    if 'variants' in bs:
        v = next(iter(bs['variants'].values()))
        if isinstance(v, list):
            v = v[0]
        return v.get('model')
    if 'multipart' in bs:
        for part in bs['multipart']:
            app = part.get('apply')
            if isinstance(app, list):
                app = app[0]
            if app and 'model' in app:
                return app['model']
    return None


def mean(a, texture):
    ns, p = split(texture)
    if not p.startswith('block/') and '/' not in p:
        p = 'block/' + p
    b = a.read(ns, f'textures/{p}.png')
    if not b:
        return None
    im = Image.open(io.BytesIO(b)).convert('RGBA')
    w, h = im.size
    im = im.crop((0, 0, w, min(h, w)))  # animated strips: the first frame
    px = [q for q in im.getdata() if q[3] > 127]
    if not px:
        return None
    # linear-light mean, back to sRGB: a far pixel averages light, not gamma-encoded values
    lin = [sum(((q[k] / 255.0) ** 2.2) for q in px) / len(px) for k in range(3)]
    return tuple(int(round((c ** (1 / 2.2)) * 255)) for c in lin)


def main():
    jar, res, out = sys.argv[1], sys.argv[2], sys.argv[3]
    a = Assets(jar, res)
    blocks = []
    for n in sorted(a.names):
        if n.startswith('assets/minecraft/blockstates/') and n.endswith('.json'):
            blocks.append(('minecraft', n.rsplit('/', 1)[1][:-5]))
    import os
    bsdir = f'{res}/assets/skycraft/blockstates'
    if os.path.isdir(bsdir):
        for f in sorted(os.listdir(bsdir)):
            if f.endswith('.json'):
                blocks.append(('skycraft', f[:-5]))
    table = {}
    for ns, name in blocks:
        model = first_model(a.json(ns, f'blockstates/{name}.json'))
        if not model:
            continue
        tex = model_textures(a, ns, model)
        t = None
        for key in ('top', 'end', 'up', 'all', 'texture', 'cross', 'side', 'particle'):
            t = resolve(tex, key)
            if isinstance(t, str) and not t.startswith('#'):
                break
            t = None
        if not t:
            continue
        rgb = mean(a, t)
        if rgb:
            table[f'{ns}:{name}'] = rgb
    keys = sorted(table)
    lines = []
    for k in keys:
        r, g, b = table[k]
        lines.append(f'            "{k}", 0x{r:02X}{g:02X}{b:02X},')
    java = f'''package com.skycraft.aether;

/**
 * Far colours of blocks (generated by native/tools/export_block_colors.py from the game's and the mod's textures; do not
 * edit): the linear-light mean of each block's top texture as sRGB, so a far column reads like the near field's blocks
 * seen from afar. Tinted textures (grass tops, leaves) are their grey: the far field applies the biome's tint itself.
 */
final class AetherBlockColors {{
    private AetherBlockColors() {{}}

    private static final java.util.Map<String, Integer> RGB = new java.util.HashMap<>({len(keys) * 2});

    static {{
        Object[] t = {{
{chr(10).join(lines)}
        }};
        for (int i = 0; i < t.length; i += 2) RGB.put((String) t[i], (Integer) t[i + 1]);
    }}

    /** sRGB of a block ("namespace:path"), or -1 when its texture is not known. */
    static int rgb(String block) {{
        Integer v = RGB.get(block);
        return v == null ? -1 : v;
    }}
}}
'''
    with open(out, 'w', encoding='utf-8', newline='\n') as f:
        f.write(java)
    print(f'{len(keys)} block colours -> {out}')


if __name__ == '__main__':
    main()
