    bool vk_ = false;
    int dims_[3] = {0, 0, 0};
    size_t nonEmpty_ = 0;
    std::vector<Dispatch> runsJobs_;  // the empty runs to measure before the next build
    size_t bricks_ = 0, resident_ = 0;  // bricks uploaded; nodes of the tree the output buffer holds
    uint32_t capNodes_ = 0, capSlices_ = 0, capParts_ = 0;
    Params params_{};
    Step stepConst_{};
    // CPU
    std::unique_ptr<Pool> pool_;
    std::vector<uint32_t> host_[B_COUNT];

    size_t bytes(int b) const { return vk_ ? size_t(vbuf_[b].size) : host_[b].size() * 4; }

    // a buffer of at least `words` words (keep: its contents survive growing)
    bool ensure(int b, size_t words, std::string& err, bool keep = false) {
        words = std::max<size_t>(words, 4);
        if (!vk_) {
            if (host_[b].size() < words) host_[b].resize(words, 0);
            return true;
        }
        return ensureVk(b, words * 4, err, keep);
    }
    bool upload(int b, const uint32_t* src, size_t words, size_t at, std::string& err) {
        if (words == 0) return true;
        if (!vk_) {
            std::memcpy(host_[b].data() + at, src, words * 4);
            return true;
        }
        return copyVk(b, src, words * 4, at * 4, true, err);
    }
    // rows (first word, words) of src into buffer b at the same places
    bool uploadRows(int b, const uint32_t* src, const std::vector<std::pair<size_t, size_t>>& rows, std::string& err) {
        if (!vk_) {
            for (auto& [at, n] : rows) std::memcpy(host_[b].data() + at, src + at, n * 4);
            return true;
        }
        size_t total = 0;
        for (auto& r : rows) total += r.second;
        if (total == 0) return true;
        if (!staging_.buf || staging_.size < total * 4) {
            releaseBuf(staging_);
            if (!createVk(staging_, std::max<size_t>(total * 4, 1 << 20), true, true, err)) return false;
        }
        std::vector<VkBufferCopy> copies;
        size_t at = 0;
        for (auto& [first, n] : rows) {
            std::memcpy(static_cast<uint8_t*>(staging_.map) + at * 4, src + first, n * 4);
            copies.push_back({at * 4, first * 4, n * 4});
            at += n;
        }
        begin();
        vkCmdCopyBuffer(cmd_, staging_.buf, vbuf_[b].buf, uint32_t(copies.size()), copies.data());
        barrier(VK_ACCESS_TRANSFER_WRITE_BIT, VK_ACCESS_SHADER_READ_BIT, VK_PIPELINE_STAGE_TRANSFER_BIT, VK_PIPELINE_STAGE_COMPUTE_SHADER_BIT);
        return submitWait(err);
    }
    bool download(int b, uint32_t* dst, size_t words, std::string& err) {
        if (words == 0) return true;
        if (!vk_) {
            std::memcpy(dst, host_[b].data(), words * 4);
            return true;
        }
        return copyVk(b, dst, words * 4, 0, false, err);
    }
    void readState(uint32_t* words) {
        if (!vk_) {
            std::memcpy(words, host_[B_STATE].data(), STATE_WORDS * 4);
            return;
        }
        std::memcpy(words, stateMap_, STATE_WORDS * 4);
    }
    bool setParams(std::string& err) {
        if (!vk_) return true;
        std::memcpy(ubo_.map, &params_, sizeof params_);
        return true;
    }

    using KernelFn = void (*)(void*, void*, void*);
    static KernelFn cpuKernel(int k) {
        static const KernelFn fns[K_COUNT] = {lbRuns,       lbErrCount, lbErrTask,  lbErrReduce, lbSliceTask,
                                              lbSliceReduce, lbSweep,    lbRegionInit, lbRegionCount, lbRegionTight,
                                              lbAdvance,    lbDescUp,   lbRootBases, lbPosDown,  lbPack,
                                              lbScanSerial, nullptr,    nullptr,    nullptr,    lbRefitBox, lbRefitPack, nullptr, nullptr,
                                              lbOctLeaf,    lbOctUp,    lbOctList,  lbOctErr,   lbOctRoot,  lbOctPos,  lbOctPack};
        return fns[k];
    }

    bool exec(const std::vector<Dispatch>& d, Stats& st, std::string& err) {
        st.dispatches += int(d.size());
        st.submits++;
        if (vk_) return execVk(d, st, err);
        Globals g{&params_, &stepConst_, {}};
        for (int b = 1; b < B_COUNT; b++) {
            size_t per = b == B_GRID || b == B_RUNS || b == B_STATE ? 1 : 4;  // uint or uint4 elements
            g.buf[b - 1] = {host_[b].data(), host_[b].size() / per};
        }
        const uint32_t* state = host_[B_STATE].data();
        for (const Dispatch& x : d) {
            uint32_t gx = x.gx, gy = x.gy;
            if (x.args >= 0) gx = state[x.args], gy = state[x.args + 1];
            if (gx == 0 || gy == 0) continue;
            std::memcpy(stepConst_.k, x.k, sizeof x.k);
            std::memcpy(stepConst_.r, x.r, sizeof x.r);
            KernelFn f = cpuKernel(x.kernel);
            // work items: up to 16 groups of one row
            uint32_t perRow = (gx + 15) / 16;
            auto t0 = std::chrono::steady_clock::now();
            pool_->run(perRow * gy, [&](uint32_t w) {
                uint32_t row = w / perRow, c = (w % perRow) * 16;
                GroupRange r{{c, row, 0}, {std::min(c + 16, gx), row + 1, 1}};
                f(&r, nullptr, &g);
            });
            if (profile) {
                st.kernelMs[x.kernel] += std::chrono::duration<double, std::milli>(std::chrono::steady_clock::now() - t0).count();
                st.kernelCalls[x.kernel]++;
            }
        }
        return true;
    }

