// a persistent pool for the CPU backend: n work items over the threads, the caller among them
class Pool {
public:
    explicit Pool(int threads) {
        for (int i = 1; i < threads; i++) ts_.emplace_back([this] { worker(); });
    }
    ~Pool() {
        {
            std::lock_guard<std::mutex> l(m_);
            quit_ = true;
        }
        cv_.notify_all();
        for (auto& t : ts_) t.join();
    }
    void run(uint32_t n, const std::function<void(uint32_t)>& f) {
        if (n == 0) return;
        if (ts_.empty() || n == 1) {
            for (uint32_t i = 0; i < n; i++) f(i);
            return;
        }
        {
            std::lock_guard<std::mutex> l(m_);
            job_ = &f;
            total_ = n;
            next_ = 0;
            active_ = int(ts_.size());
            gen_++;
        }
        cv_.notify_all();
        for (uint32_t i; (i = next_++) < n;) f(i);
        std::unique_lock<std::mutex> l(m_);
        done_.wait(l, [&] { return active_ == 0; });
        job_ = nullptr;
    }

private:
    void worker() {
        uint64_t seen = 0;
        for (;;) {
            const std::function<void(uint32_t)>* f;
            uint32_t n;
            {
                std::unique_lock<std::mutex> l(m_);
                cv_.wait(l, [&] { return quit_ || gen_ != seen; });
                if (quit_) return;
                seen = gen_;
                f = job_;
                n = total_;
            }
            for (uint32_t i; (i = next_++) < n;) (*f)(i);
            std::lock_guard<std::mutex> l(m_);
            if (--active_ == 0) done_.notify_one();
        }
    }
    std::vector<std::thread> ts_;
    std::mutex m_;
    std::condition_variable cv_, done_;
    const std::function<void(uint32_t)>* job_ = nullptr;
    uint32_t total_ = 0;
    std::atomic<uint32_t> next_{0};
    int active_ = 0;
    uint64_t gen_ = 0;
    bool quit_ = false;
};

