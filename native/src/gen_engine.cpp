// The client's world generator (atlas_gen_*, docs/ATLAS-CLIENT-GENERATION.md): shaders/atlas_gen.slang on its own
// Vulkan compute device, or the same kernels compiled to C++. Self-contained like the height engine: the mod's worker
// threads call it; calls on one handle serialise. atlas_gen_into hands the sections to a context through the same
// internal path atlas_upload_section takes (World::putSection + the level-0 grid's put).
