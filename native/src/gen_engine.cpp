constexpr uint32_t GROUP = 64;
constexpr uint32_t MAX_CHUNKS = 64;     // per submission
constexpr uint32_t CORNERS = 2025, AQ_WORDS = 513 * 5 + 4, BLOCK_WORDS = 16 * 16 * 640, COL_WORDS = 256 + 8;
constexpr uint32_t OUT_WORDS = 40 * 2048;
constexpr uint32_t INFO_WORDS = 4 + 40 * 4;  // atlas_gen.slang secInfo
constexpr uint32_t PASSES = 6;               // the terrain's; then INGEST_PASSES (cols, secs, mats), then the math check
constexpr uint32_t INGEST_PASSES = 3;
constexpr uint32_t PACK_PASS = 5;  // (the passes: corners, aquifer, fill, tops, surface, pack): the stages run before it
constexpr uint32_t PIPES = PASSES + INGEST_PASSES + 8;
constexpr uint32_t MATH_PIPE = PASSES + INGEST_PASSES, PROBE_PIPE = MATH_PIPE + 1;
constexpr uint32_t PAGECOLS_PIPE = PROBE_PIPE + 1, PAGEBIOMES_PIPE = PROBE_PIPE + 2;  // the pages on the device
constexpr uint32_t TILE_PIPE = PROBE_PIPE + 3, TILESURF_PIPE = PROBE_PIPE + 4, TILEBIOME_PIPE = PROBE_PIPE + 5;  // far tiles
constexpr uint32_t FARCHUNK_PIPE = PROBE_PIPE + 6;  // far chunks (atlas_gen_far)
// columns of a tile; its planes (surface, water, top | under, biome, the under biome); tiles of one dispatch
constexpr uint32_t TILE_COLS = 65536, TILE_PLANES = 7, TILE_MAX = 16;  // (5, 6: the far stages' canopy)
constexpr uint32_t NB = 15;  // storage buffer bindings
constexpr uint32_t QUERIES = 2 * (PASSES + INGEST_PASSES) + 4;  // each pass's start and end, the readback's end, the pages' two
constexpr uint32_t PROBE_WORDS = 32;  // atlas_gen.slang probeMain
constexpr uint32_t QY = 176;
constexpr uint32_t H_K = 3, H_FIELDS = 13, MAGIC = 0x4E454741u;
constexpr uint32_t S_PAGEGEN = 113;  // atlas_page.slang: nonzero when the program carries the page passes' inputs
constexpr VkDeviceSize SECTION_BYTES = 8192;
// the chunk store (atlas.h atlas_gen_store_*): per slot the terrain as made (16-bit ids), the working blocks (32-bit:
// priority << 16 | id) and the aux words (the quart biomes); a store stage's radius at most STORE_RMAX
constexpr uint32_t STORE_TERRAIN_WORDS = BLOCK_WORDS / 2, STORE_AUX_WORDS = 2048, STORE_RMAX = 8;
static_assert(STORE_TERRAIN_WORDS == ATLAS_GEN_STORE_TERRAIN_WORDS && BLOCK_WORDS == ATLAS_GEN_STORE_BLOCK_WORDS &&
                  STORE_AUX_WORDS == ATLAS_GEN_STORE_AUX_WORDS, "atlas.h's store layout");
struct StoreParams {
    int32_t count, pageMinCx, pageMinCz, pageW, pageH;
    uint32_t pageWords, quartOffset, base;
};

double msSince(std::chrono::steady_clock::time_point t0) {
    return std::chrono::duration<double, std::milli>(std::chrono::steady_clock::now() - t0).count();
}

template <typename T>
struct CpuBuf {
    T* data;
    size_t count;
};
struct GenParams {
    int32_t chunks, pageMinCx, pageMinCz, pageW, pageH;
    uint32_t outMode;
    int32_t pad0, pad1;
};
// Must list the globals of atlas_gen.slang in declaration order.
struct GenGlobals {
    const GenParams* params;
    CpuBuf<const uint32_t> prog;
    CpuBuf<uint32_t> pages;
    CpuBuf<const int32_t> pageIndex;
    CpuBuf<const int32_t> chunkList;
    CpuBuf<float> corners;
    CpuBuf<int32_t> aq;
    CpuBuf<uint32_t> blocks;
    CpuBuf<int32_t> colInfo;
    CpuBuf<uint32_t> out;
    CpuBuf<const uint32_t> ingestTab;
    CpuBuf<uint32_t> secInfo;
    CpuBuf<const uint32_t> mapData;
    CpuBuf<const int32_t> pageJobs;
    CpuBuf<uint32_t> pageBad;
    CpuBuf<uint32_t> farOut;
};

// threads per chunk of each pass (dispatch x = ceil / 64, y = chunks): the terrain's, then the ingest's
constexpr uint32_t PASS_ITEMS[PASSES + INGEST_PASSES] = {CORNERS, 514, BLOCK_WORDS, 256, 256, OUT_WORDS, 256, 40, OUT_WORDS};

uint32_t pageWordsOf(const std::vector<uint32_t>& prog) {
    return prog.size() > H_FIELDS ? prog[H_FIELDS] * 256u + 256u + 4u * 4u * QY / 2u : 0u;
}

// One batch's inputs, as both engines take them
struct Batch {
    GenParams params{};
    std::vector<int32_t> pageIndex;
    std::vector<int32_t> chunks;
    // pages the engine makes first (the map set: atlas_page.slang), (cx, cz, slot, full) each
    std::vector<int32_t> jobs;
    // (atlas_gen_run) each chunk's 40 sections' kinds (SEC_*), for the ingest's uniform hints
    std::vector<uint8_t> kinds;
    // (the self-baking cache, gencache.hpp) per chunk: its sections with blocks packed for the world's gen cache
    std::vector<uint8_t> bake;
    // the chunk store: 0 a plain batch; 1 its terrain into the store (no pack); 2 its chunks out of the store (the
    // pack and the ingest passes only); storeItems (batch chunk, slot, cx, cz) per chunk
    int mode = 0;
    std::vector<int32_t> storeItems;
};

// What a run hands back: ids (null: not wanted) n * OUT_WORDS words; flags n words; info (null: no ingest passes)
// n * INFO_WORDS words, the kernels' raw secInfo
struct RunOut {
    uint32_t* ids = nullptr;
    uint32_t* flags = nullptr;
    uint32_t* info = nullptr;
    uint32_t* jobBad = nullptr;  // per page job: nonzero where a value is not proven exact
    double pageMs = 0;           // the page passes (device timestamps or CPU wall)
};

// A registered stage of the batch (atlas_gen_add_stage): its order, the engine's callback, its data, its id; a store
// stage (atlas_gen_add_store_stage) its radius and store callback instead
struct Stage {
    uint32_t order, id;
    AtlasGenStageFn fn;
    void* user;
    bool store = false;
    uint32_t radius = 0;
    AtlasGenStoreStageFn sfn = nullptr;
    AtlasGenFarStageFn ffn = nullptr;  // a far stage (atlas_gen_add_far_stage): neither a batch's nor the store's
    uint64_t fp = 0;                   // (a far stage) its fingerprint
};

class Engine {
public:
    virtual ~Engine() = default;
    // the stages the batch runs between the terrain and its sections (sorted by order; GPU engines only)
    virtual bool setStages(const std::vector<Stage>& stages, std::string& err) {
        if (!stages.empty()) return (err = "stages run on a Vulkan generator only"), false;
        return true;
    }
    // the device the stages' engines make their pipelines on (atlas_gen_device_handles)
    virtual bool deviceHandles(AtlasGenDevice& out) {
        (void)out;
        return false;
    }
    // the submissions whose fence passed (atlas_gen_completed_submissions; any thread, no lock)
    virtual uint64_t completedSubmissions() const { return UINT64_MAX; }
    // the chunk store (GPU only): its slots; one store stage's call over `count` chunks ((cx, cz, slot) each) with
    // their neighbourhoods ((2 r + 1)^2 slots each)
    virtual bool storeEnable(uint32_t slots, std::string& err) {
        (void)slots;
        err = "the chunk store is on the GPU only";
        return false;
    }
    virtual bool storeStage(const Stage& st, uint32_t count, const std::vector<int32_t>& list, const std::vector<int32_t>& nb,
                            std::string& err) {
        (void)st, (void)count, (void)list, (void)nb;
        err = "the chunk store is on the GPU only";
        return false;
    }
    virtual const char* device() const = 0;
    virtual bool setProgram(const std::vector<uint32_t>& prog, std::string& err) = 0;
    virtual bool setPage(uint32_t slot, const uint32_t* words, std::string& err) = 0;
    virtual bool setIngest(const std::vector<uint32_t>& tab, std::string& err) = 0;
    virtual bool setMap(const std::vector<uint32_t>& map, std::string& err) = 0;
    // probes (atlas_gen_probe): n (x, z) pairs, PROBE_WORDS out each
    virtual bool probe(uint32_t kind, uint32_t n, const int32_t* xz, uint32_t* out, std::string& err) = 0;
    virtual bool run(const Batch& b, RunOut& o, AtlasGenTimes& t, std::string& err) = 0;
    // a resident page's words (atlas_gen_read_page)
    virtual bool readPage(uint32_t slot, uint32_t* out, std::string& err) = 0;
    // far tiles (atlas_gen_tiles): jobs (lod, tx, tz, 0) each, n <= TILE_MAX; out n * TILE_PLANES * TILE_COLS words
    // (the surface pass only when blocks); bad n words
    virtual bool tiles(const std::vector<int32_t>& jobs, bool blocks, uint32_t* out, uint32_t* bad, double& ms, std::string& err) = 0;
    // far chunks (atlas_gen_far, the GPU only): the tile passes, then farChunkMain over the jobs' level-k chunks; kinds
    // n * 256 * rows * 2 words (kind, slot), ids cap * 2048 words, mixed: the slots used (may exceed cap: ask again)
    virtual bool far(const std::vector<int32_t>& jobs, uint32_t rows, uint32_t mode, uint32_t cap, uint32_t* kinds, uint32_t* ids,
                     uint32_t& mixed, uint32_t* bad, double& ms, std::string& err) {
        (void)jobs, (void)rows, (void)mode, (void)cap, (void)kinds, (void)ids, (void)mixed, (void)bad, (void)ms;
        err = "far chunks are made on the GPU only";
        return false;
    }
    // the math check: prog = n argument pairs, out = 3 words each (atlas_gen_math)
    virtual bool math(uint32_t op, uint32_t n, const std::vector<uint32_t>& args, uint32_t* out, std::string& err) = 0;
    // the last ingest run's sections (chunk c's section s where masks[c] bit s), to the context: count sent
    // (masks in / out: on return the bits of the sections that went)
    virtual bool ingest(AtlasContext* ctx, const Batch& b, uint64_t* masks, uint32_t& sent, std::string& err) = 0;
    // far chunks into the context's grid (atlas_gen_far_ingest, GPU only): far()'s passes into a slab the grid reads,
    // then VoxGrid::ingestCoarseGpu; kinds as far()'s; taken: the chunks the grid took
    // (the self-baking cache) where farIngest bakes the tiles it lacks (null: none)
    GenCache* farBake = nullptr;
    // (the idle verifier, atlas_gen_verify_far_tile) set for one farIngest call: the tile made is compared with the cache's
    // instead of going into the grid; -1 not comparable, 0 the same, 1 it differed (and was baked again)
    int32_t* verifyResult = nullptr;
    // the GPU budget (VulkanEngine's pacer): the class of the work submitted from now (0 the near terrain, 1 the far
    // field: it takes only what the near work left), and the pacer's numbers (atlas_gen_pace_stats)
    virtual void paceClass(int c) { (void)c; }
    // the loading phase (a screen holds the player: no frame to keep): every submission of the generator unpaced, the near
    // window's too (any thread)
    virtual void setBoost(bool on) { (void)on; }
    struct PaceStats {
        double periodMs = 0, duty = 1, tokensMs = 0, usedMs = 0, waitedMs = 0, farWaitedMs = 0, maxSubMs = 0;
        uint64_t submissions = 0;
        char maxPhase[48] = {};  // what the longest submission was
        double frameGpuMs = 0;
        double recentMaxMs = 0;  // the longest of the last 10-20 s, and what it was
        char recentPhase[48] = {};
    };
    virtual PaceStats paceStats() const { return {}; }
    // the submissions' GPU times by what they held (a phase class: "far stage", "store stage 1000" ...) since the last reset:
    // one line, the longest classes first (atlas_gen_sub_stats; any thread, no generator lock)
    virtual size_t subStats(char* out, size_t cap, bool reset) {
        (void)reset;
        if (cap) out[0] = 0;
        return 0;
    }
    virtual bool stageInParts(uint32_t) const { return false; }  // (a store stage seen recording in parts)
    virtual bool farIngest(const std::vector<int32_t>& jobs, int lod, uint32_t rows, uint32_t cap, uint32_t* kinds, uint32_t& mixed,
                           uint32_t& taken, uint32_t* bad, double& ms, std::string& err) {
        (void)jobs, (void)lod, (void)rows, (void)cap, (void)kinds, (void)mixed, (void)taken, (void)bad, (void)ms;
        err = "far chunks go into a grid on a Vulkan context only";
        return false;
    }
    // the grid's dropped / wanted sections and chunks ({level, x, y, z}): what to make and send again
    virtual void takeGridReports(std::vector<std::array<int32_t, 4>>& dropped, std::vector<std::array<int32_t, 4>>& wanted) {
        dropped.clear();
        wanted.clear();
    }
};

class CpuEngine final : public Engine {
public:
    explicit CpuEngine(uint32_t slots) : slots_(slots) {}
    const char* device() const override { return "cpu (slang->c++)"; }
    bool setProgram(const std::vector<uint32_t>& prog, std::string&) override {
        prog_ = prog;
        pageWords_ = pageWordsOf(prog_);
        pages_.assign(size_t(slots_) * pageWords_, 0u);
        return true;
    }
    bool setPage(uint32_t slot, const uint32_t* words, std::string&) override {
        std::memcpy(pages_.data() + size_t(slot) * pageWords_, words, size_t(pageWords_) * 4);
        return true;
    }
    bool setIngest(const std::vector<uint32_t>& tab, std::string&) override {
        tab_ = tab;
        return true;
    }
    bool setMap(const std::vector<uint32_t>& map, std::string&) override {
        map_ = map;
        return true;
    }
    bool probe(uint32_t kind, uint32_t n, const int32_t* xz, uint32_t* out, std::string&) override {
        GenParams p{int32_t(n), 0, 0, 0, 0, kind, 0, 0};
        std::vector<int32_t> none(2, 0);
        float f = 0;
        int32_t i32 = 0;
        uint32_t u32 = 0, u32b = 0;
        GenGlobals g{&p, {prog_.data(), prog_.size()}, {pages_.data(), pages_.size()}, {xz, size_t(n) * 2}, {none.data(), 1}, {&f, 1},
                     {&i32, 1}, {&u32, 1}, {&i32, 1}, {out, size_t(n) * PROBE_WORDS}, {tab_.data(), tab_.size()}, {&u32b, 1},
                     {map_.data(), map_.size()}, {none.data(), 1}, {&u32, 1}, {&u32b, 1}};
        uint32_t groups = (n + GROUP - 1) / GROUP;
        std::atomic<uint32_t> next{0};
        auto worker = [&] {
            for (;;) {
                uint32_t g0 = next.fetch_add(16);
                if (g0 >= groups) return;
                AtlasGenGroupRange r{{g0, 0, 0}, {std::min(groups, g0 + 16), 1, 1}};
                probeMain(&r, nullptr, &g);
            }
        };
        parallelRun(worker, 16);
        return true;
    }
    bool readPage(uint32_t slot, uint32_t* out, std::string&) override {
        std::memcpy(out, pages_.data() + size_t(slot) * pageWords_, size_t(pageWords_) * 4);
        return true;
    }
    bool tiles(const std::vector<int32_t>& jobs, bool blocks, uint32_t* out, uint32_t* bad, double& ms, std::string&) override {
        auto t0 = std::chrono::steady_clock::now();
        uint32_t n = uint32_t(jobs.size() / 4);
        GenParams p{int32_t(n), 0, 0, 0, 0, 0, 0, 0};
        std::vector<int32_t> none(2, 0);
        std::vector<uint32_t> flags(std::max<uint32_t>(n, 1), 0u);
        float f = 0;
        int32_t i32 = 0;
        uint32_t u32 = 0;
        GenGlobals g{&p, {prog_.data(), prog_.size()}, {pages_.data(), pages_.size()}, {none.data(), 1}, {none.data(), 1}, {&f, 1},
                     {&i32, 1}, {&u32, 1}, {&i32, 1}, {out, size_t(n) * TILE_PLANES * TILE_COLS}, {tab_.data(), tab_.size()}, {&u32, 1},
                     {map_.data(), map_.size()}, {jobs.data(), jobs.size()}, {flags.data(), flags.size()}, {&u32, 1}};
        for (int pass = 0; pass < (blocks ? 3 : 1); pass++) {
            uint32_t groupsX = (pass == 1 ? 3 : 1) * TILE_COLS / GROUP, total = groupsX * n;
            std::atomic<uint32_t> next{0};
            auto worker = [&] {
                for (;;) {
                    uint32_t g0 = next.fetch_add(8);
                    if (g0 >= total) return;
                    for (uint32_t gi = g0; gi < std::min(total, g0 + 8); gi++) {
                        AtlasGenGroupRange r{{gi % groupsX, gi / groupsX, 0}, {gi % groupsX + 1, gi / groupsX + 1, 1}};
                        (pass == 0 ? tileMain : pass == 1 ? tileBiomeMain : tileSurfMain)(&r, nullptr, &g);
                    }
                }
            };
            parallelRun(worker, 16);
        }
        std::memcpy(bad, flags.data(), size_t(n) * 4);
        ms = msSince(t0);
        return true;
    }
    bool run(const Batch& b, RunOut& o, AtlasGenTimes& t, std::string&) override {
        uint32_t n = uint32_t(b.params.chunks);
        uint32_t K = prog_[H_K];
        uint32_t nj = uint32_t(b.jobs.size() / 4);
        if (nj) {
            // the pages first: their fields and water, then (full pages) the quart biomes, which read the fields
            auto p0 = std::chrono::steady_clock::now();
            GenParams pp = b.params;
            pp.chunks = int32_t(nj);
            bad_.assign(slots_, 0u);
            std::vector<int32_t> none(2, 0);
            float f = 0;
            int32_t i32 = 0;
            uint32_t u32 = 0;
            GenGlobals g{&pp, {prog_.data(), prog_.size()}, {pages_.data(), pages_.size()}, {b.pageIndex.data(), b.pageIndex.size()},
                         {b.chunks.data(), b.chunks.size()}, {&f, 1}, {&i32, 1}, {&u32, 1}, {&i32, 1}, {&u32, 1},
                         {tab_.data(), tab_.size()}, {&u32, 1}, {map_.data(), map_.size()}, {b.jobs.data(), b.jobs.size()},
                         {bad_.data(), bad_.size()}, {&u32, 1}};
            for (int pass = 0; pass < 2; pass++) {
                uint32_t groupsX = pass == 0 ? 256 / GROUP : (nj * 16 + GROUP - 1) / GROUP, groupsY = pass == 0 ? nj : 1;
                uint32_t total = groupsX * groupsY;
                std::atomic<uint32_t> next{0};
                auto worker = [&] {
                    for (;;) {
                        uint32_t g0 = next.fetch_add(2);
                        if (g0 >= total) return;
                        for (uint32_t gi = g0; gi < std::min(total, g0 + 2); gi++) {
                            uint32_t gx = gi % groupsX, gy = gi / groupsX;
                            AtlasGenGroupRange r{{gx, gy, 0}, {gx + 1, gy + 1, 1}};
                            (pass == 0 ? pageColsMain : pageBiomesMain)(&r, nullptr, &g);
                        }
                    }
                };
                parallelRun(worker, 16);
            }
            if (o.jobBad)
                for (uint32_t j = 0; j < nj; j++) o.jobBad[j] = bad_[uint32_t(b.jobs[j * 4 + 2])];
            o.pageMs = msSince(p0);
            t.kernelMs += o.pageMs;
        }
        bool ingest = o.info != nullptr;
        corners_.assign(size_t(n) * CORNERS * std::max<uint32_t>(K, 1u), 0.0f);
        aq_.assign(size_t(n) * AQ_WORDS, 0);
        blocks_.assign(size_t(n) * BLOCK_WORDS, 0u);
        col_.assign(size_t(n) * COL_WORDS, 0);
        out_.assign(size_t(n) * OUT_WORDS + n, 0u);
        info_.assign(size_t(n) * INFO_WORDS, 0xFFFFFFFFu);
        GenGlobals g{&b.params,
                     {prog_.data(), prog_.size()},
                     {pages_.data(), pages_.size()},
                     {b.pageIndex.data(), b.pageIndex.size()},
                     {b.chunks.data(), b.chunks.size()},
                     {corners_.data(), corners_.size()},
                     {aq_.data(), aq_.size()},
                     {blocks_.data(), blocks_.size()},
                     {col_.data(), col_.size()},
                     {out_.data(), out_.size()},
                     {tab_.data(), tab_.size()},
                     {info_.data(), info_.size()},
                     {map_.data(), map_.size()},
                     {b.jobs.data(), std::max<size_t>(b.jobs.size(), 1)},
                     {bad_.data(), bad_.size()},
                     {&farNone_, 1}};
        void (*fns[PASSES + INGEST_PASSES])(void*, void*, void*) = {cornerMain, aquiferMain, fillMain, topMain, surfaceMain,
                                                                    packMain, colsMain, secsMain, matsMain};
        for (uint32_t p = 0; p < (ingest ? PASSES + INGEST_PASSES : PASSES); p++) {
            if (p == PASSES && o.ids) std::memcpy(o.ids, out_.data(), size_t(n) * OUT_WORDS * 4);  // before the materials
            auto t0 = std::chrono::steady_clock::now();
            uint32_t groups = (PASS_ITEMS[p] + GROUP - 1) / GROUP;
            uint32_t total = groups * n;
            std::atomic<uint32_t> next{0};
            auto worker = [&] {
                for (;;) {
                    uint32_t g0 = next.fetch_add(4);
                    if (g0 >= total) return;
                    for (uint32_t gi = g0; gi < std::min(total, g0 + 4); gi++) {
                        uint32_t gx = gi % groups, gy = gi / groups;
                        AtlasGenGroupRange r{{gx, gy, 0}, {gx + 1, gy + 1, 1}};
                        fns[p](&r, nullptr, &g);
                    }
                }
            };
            parallelRun(worker, 16);
            double ms = msSince(t0);
            if (p < PASSES) t.passMs[p] = ms;
            t.kernelMs += ms;
        }
        if (!ingest && o.ids) std::memcpy(o.ids, out_.data(), size_t(n) * OUT_WORDS * 4);
        if (o.flags) std::memcpy(o.flags, out_.data() + size_t(n) * OUT_WORDS, size_t(n) * 4);
        if (ingest) std::memcpy(o.info, info_.data(), info_.size() * 4);
        return true;
    }

    bool math(uint32_t op, uint32_t n, const std::vector<uint32_t>& args, uint32_t* out, std::string&) override {
        GenParams p{int32_t(n), 0, 0, 0, 0, op, 0, 0};
        std::vector<int32_t> none(2, 0);
        float f = 0;
        int32_t i32 = 0;
        uint32_t u32 = 0, u32b = 0;
        GenGlobals g{&p, {args.data(), args.size()}, {&u32, 1}, {none.data(), 1}, {none.data(), 1}, {&f, 1}, {&i32, 1}, {&u32, 1},
                     {&i32, 1}, {out, size_t(n) * 3}, {&u32, 1}, {&u32b, 1}, {&u32, 1}, {none.data(), 1}, {&u32b, 1}, {&u32b, 1}};
        uint32_t groups = (n + GROUP - 1) / GROUP;
        std::atomic<uint32_t> next{0};
        auto worker = [&] {
            for (;;) {
                uint32_t g0 = next.fetch_add(64);
                if (g0 >= groups) return;
                AtlasGenGroupRange r{{g0, 0, 0}, {std::min(groups, g0 + 64), 1, 1}};
                mathMain(&r, nullptr, &g);
            }
        };
        parallelRun(worker, 16);
        return true;
    }

    // the CPU backend's context: the materials go up as atlas_upload_section takes them
    bool ingest(AtlasContext* ctx, const Batch& b, uint64_t* masks, uint32_t& sent, std::string& err) override {
        uint32_t n = uint32_t(b.params.chunks);
        if (out_.size() < size_t(n) * OUT_WORDS) return (err = "no run to ingest"), false;
        for (uint32_t i = 0; i < n; i++)
            for (uint32_t s = 0; s < 40; s++) {
                if (!((masks[i] >> s) & 1u)) continue;
                const uint16_t* m = reinterpret_cast<const uint16_t*>(out_.data() + size_t(i) * OUT_WORDS + size_t(s) * 2048);
                if (atlas_upload_section(ctx, b.chunks[i * 2], int32_t(s) - 4, b.chunks[i * 2 + 1], m) != ATLAS_OK)
                    return (err = "section upload failed"), false;
                sent++;
            }
        return true;
    }

private:
    uint32_t slots_;
    std::vector<uint32_t> prog_ = std::vector<uint32_t>(64, 0u);
    uint32_t pageWords_ = 0;
    std::vector<uint32_t> pages_, tab_ = std::vector<uint32_t>(4, 0u), map_ = std::vector<uint32_t>(64, 0u);
    std::vector<float> corners_;
    std::vector<int32_t> aq_, col_;
    std::vector<uint32_t> blocks_, out_, info_, bad_ = std::vector<uint32_t>(1, 0u);
    uint32_t farNone_ = 0;
};

