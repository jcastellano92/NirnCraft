// The client's world generator (atlas_gen_*, docs/ATLAS-CLIENT-GENERATION.md): shaders/atlas_gen.slang on a Vulkan
// compute device, or the same kernels compiled to C++. Self-contained like the height engine (atlas_gen_create: its own
// device), or on a context's own device (atlas_gen_create_for): the sections then go from the kernels' output straight
// into the context's grid, device to device (atlas_gen_run + atlas_gen_ingest, VoxGrid::ingestGpu). The mod's worker
// threads call it; calls on one handle serialise. atlas_gen_into hands the sections to a context through the same
// internal path atlas_upload_section takes (World::putSection + the level-0 grid's put).
