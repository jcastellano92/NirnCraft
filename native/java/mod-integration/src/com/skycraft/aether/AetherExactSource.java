package com.skycraft.aether;

import com.skycraft.tamriel.MapSample;
import com.skycraft.tamriel.TamrielMap;
import com.skycraft.tamriel.terrain.TamrielHeight;
import com.skycraft.worldgen.WorldNoise;
import net.minecraft.core.registries.Registries;
import net.minecraft.resources.Identifier;
import net.minecraft.resources.ResourceKey;
import net.minecraft.server.MinecraftServer;
import net.minecraft.server.level.ServerLevel;
import net.minecraft.world.level.levelgen.NoiseBasedChunkGenerator;
import net.minecraft.world.level.levelgen.NoiseGeneratorSettings;
import net.minecraft.world.level.levelgen.RandomState;

import java.nio.file.Path;
import java.util.concurrent.Callable;
import java.util.concurrent.ForkJoinPool;
import java.util.stream.IntStream;

/**
 * Exact far-field columns in single player: the overworld's own terrain height, skycraft:tamriel_height bound to the
 * world's seeded noises (the 2D surface the generator's final density is built on), evaluated per far column on a
 * small worker pool. The geometry is exact; caves and the 3D overhang term are left out (sub-voxel past the near
 * field). Materials and forest canopy are aether's preview dressing from the same map raster. The raster stand-in
 * shows first and is refined tile by tile (AetherRefiningSource), so the horizon is never empty while this computes.
 */
final class AetherExactSource extends AetherRefiningSource {
    /** The seeded noises of skycraft:tamriel_height (worldgen/density_function/tamriel/height.json), in record order. */
    static final String[] NOISES = {"tamriel_hills", "tamriel_detail", "tamriel_ridges", "tamriel_dunes"};
    static final ResourceKey<NoiseGeneratorSettings> TAMRIEL =
            ResourceKey.create(Registries.NOISE_SETTINGS, Identifier.fromNamespaceAndPath("skycraft", "tamriel"));

    private static final int TILE = AetherNative.TILE;

    private final TamrielHeight height;
    private final ForkJoinPool pool;
    private final float[] surface = new float[TILE * TILE], water = new float[TILE * TILE];

    /** raster: the preview raster aether dresses the columns from (AetherRasterCache.ensure in game). */
    AetherExactSource(TamrielHeight height, Callable<Path> raster, int threads) {
        super(raster);
        this.height = height;
        pool = new ForkJoinPool(Math.max(1, threads), p -> {
            var t = ForkJoinPool.defaultForkJoinWorkerThreadFactory.newThread(p);
            t.setName("skycraft-aether-columns-" + t.getPoolIndex());
            t.setDaemon(true);
            t.setPriority(Thread.NORM_PRIORITY - 1);
            return t;
        }, null, false);
    }

    /**
     * The overworld's terrain height, or null when that world is not generated by Skycraft's Tamriel settings
     * (another preset, a datapack world). Uses the server's own RandomState, so the noises are the very instances its
     * chunk generator samples.
     */
    static TamrielHeight heightOf(MinecraftServer server) {
        ServerLevel overworld = server.overworld();
        if (!(overworld.getChunkSource().getGenerator() instanceof NoiseBasedChunkGenerator g) || !g.stable(TAMRIEL))
            return null;
        RandomState rs = overworld.getChunkSource().randomState();
        WorldNoise[] n = new WorldNoise[NOISES.length];
        for (int i = 0; i < n.length; i++)
            n[i] = new WorldNoise(null, rs.getOrCreateNoise(ResourceKey.create(Registries.NOISE,
                    Identifier.fromNamespaceAndPath("skycraft", NOISES[i]))));
        return new TamrielHeight(n[0], n[1], n[2], n[3]);
    }

    /** Column threads: a quarter of the cores, leaving the rest to the server's chunk generation. */
    static int defaultThreads() {
        return Integer.getInteger("skycraft.aether.columnThreads", Math.max(1, Runtime.getRuntime().availableProcessors() / 4));
    }

    /** The integrated server's exact source, or null when its overworld is not a Tamriel world. */
    static AetherExactSource forServer(MinecraftServer server, Callable<Path> raster) {
        TamrielHeight h = heightOf(server);
        return h == null ? null : new AetherExactSource(h, raster, defaultThreads());
    }

    @Override
    Refined refine(AetherNative.Context ctx, int lod, int tx, int tz) {
        fill(lod, tx, tz, surface, water);
        AetherTileCodec.quantize(lod, surface, water);  // as a server would send it: SP and MP far fields match
        ctx.uploadColumnHeights(lod, tx, tz, surface, water);
        return Refined.DONE;
    }

    @Override
    int budget(int lod) {
        return 3;  // ~0.1 s of columns between clipmap rebuilds
    }

    /** Surface and water of tile (lod, tx, tz): column (i, j) sampled at its centre block, row-major [j][i]. */
    void fill(int lod, int tx, int tz, float[] surface, float[] water) {
        int s = 1 << lod, bx = tx * (TILE << lod) + (s >> 1), bz = tz * (TILE << lod) + (s >> 1);
        pool.submit(() -> IntStream.range(0, TILE).parallel().forEach(j -> {
            MapSample m = new MapSample();
            for (int i = 0; i < TILE; i++) {
                int x = bx + i * s, z = bz + j * s;
                TamrielMap.sample(x, z, m);
                double h = height.height(x, z, m);
                surface[j * TILE + i] = (float) h;
                water[j * TILE + i] = waterAt(h, m);
            }
        })).join();
    }

    /**
     * The water surface over a column, NaN when dry: the sea (and the near-surface aquifers, which hold sea level)
     * fill below y 63; rivers and lakes above it stand at the map's water level, filled up to block ceil(level) - 1
     * like MapWaterFeature does.
     */
    static float waterAt(double h, MapSample m) {
        float w = h < TamrielMap.SEA_LEVEL ? TamrielMap.SEA_LEVEL : Float.NaN;
        if (m.inWater() && m.waterLevel >= TamrielMap.SEA_LEVEL) {
            float top = (float) Math.ceil(m.waterLevel);
            w = Float.isNaN(w) ? top : Math.max(w, top);
        }
        return w > h ? w : Float.NaN;
    }

    @Override
    public void close() {
        pool.shutdownNow();
    }
}
